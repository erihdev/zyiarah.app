/// جمهورُ البثِّ الإداريِّ: **قيمةٌ واحدةٌ في الوثيقة، واسمُ الموضوعِ شيءٌ آخر.**
///
/// الخادمُ يَعرفُ أربعَ قيمٍ (`validTargets` في `functions/index.js`):
/// `all` و`clients` و`drivers` و`admins`. أمّا `all_users` فهو **اسمُ موضوعِ
/// FCM** الذي يَشترِكُ فيه الجهازُ (`notification_service`)، ويَستعملُه
/// `manualSendNotification` موضوعاً لا حقلاً (`target === "all" ? "all_users"`).
/// وشاشةُ البثِّ تَحملُ `_target = 'all_users'` قيمةَ واجهةٍ ثمّ **تُحوّلُها**
/// قبلَ الكتابة.
///
/// **والتحويلُ كان في اثنَين من ثلاثةِ كُتّابٍ (2026-10-07):** المسارُ الفوريُّ
/// والمنبثقُ يُحوّلان، والمسارُ **المجدولُ** يُمرّرُ `_target` كما هو إلى
/// `scheduleBroadcast` فيُكتَبُ `all_users` في `notifications_log.target`.
/// فجمهورٌ واحدٌ بتهجئتَين في الحقلِ نفسِه. وأثرُه:
///
///  1. **التسليمُ صحيحٌ بالمصادفةِ لا بالقرار:** `_deliverBroadcast` يَتفرّعُ
///     على الثلاثةِ المعروفةِ ويَترُكُ الاستعلامَ **بلا مُرشِّحٍ** فيما سوى
///     ذلك — أي «الجميع». فالنتيجةُ هي المقصودةُ، لكنّ إضافةَ فرعٍ رابعٍ أو
///     تحقّقٍ هناك تُحوّلُ كلَّ بثٍّ مجدولٍ «للجميع» إلى جمهورٍ آخرَ بصمت.
///  2. وسجلُّ لوحةِ الويبِ يَطبعُ الرمزَ الداخليَّ `all_users` حرفيّاً في
///     واجهةٍ عربيّة (دالّةُ التسميةِ تُعيدُ ما لا تَعرفُه كما هو).
///
/// فالقاعدةُ هنا، ويُنادِيها **كلُّ** كاتبٍ لذلك الحقل.
library;

/// القيمُ التي يَعرفُها الخادم — مرآةُ `validTargets` في `functions/index.js`،
/// ويَشدُّ التطابقَ `test/broadcast_target_test.dart`.
const Set<String> kBroadcastTargets = {'all', 'clients', 'drivers', 'admins'};

/// القيمةُ التي تُكتَبُ في `notifications_log.target`.
///
/// غيرُ المعروفِ يُقرأُ «الجميع» — **وهو قرارٌ لا تسامُح**: بثٌّ لا يَصِلُ
/// أحداً أسوأُ من بثٍّ يَصِلُ أكثرَ من المقصود، وهو كذلك ما يَفعلُه الخادمُ
/// اليومَ للمستنداتِ القائمةِ التي تَحملُ `all_users`.
String broadcastTargetOf(String uiValue) {
  final String v = uiValue.trim();
  if (kBroadcastTargets.contains(v)) return v;
  return 'all';
}
