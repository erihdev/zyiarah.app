/// **بوّابةُ الإصدار: رقمُ بناءٍ منشورٍ واحدٌ يُقرَّر، والصفرُ غياب.**
///
/// `system_configs/app_update` هو المفتاحُ الذي يُجبرُ العملاءَ على التحديث،
/// وهو **الشرطُ المُعلَنُ لنشرِ أربعِ قواعدِ أمانٍ** محجوزةٍ في
/// `firestore.rules` (حجزُ STAGE-C: القاعدةُ الجديدةُ تَكسرُ النسخَ القديمةَ
/// حتى يَصيرَ البناءُ الجديدُ هو الحدَّ الأدنى). فعطلٌ صامتٌ هنا ليس إزعاجاً
/// مؤجَّلاً: إنّه إمّا بوّابةٌ لا تُغلَق — فتُنشَرُ القاعدةُ على مستخدمينَ لم
/// يُحدِّثوا — أو مطالبةٌ زائفةٌ لمن حدَّث، وقد وقعت فعلاً (2026-08-31).
///
/// وقد عَطبَ هذا الملفُّ **مرّتَين** قبلَ وجودِه، والثانيةُ أدخلَها إصلاحُ
/// الأولى:
///
///   ١) قبلَ 2026-10-04 كتبَ المحرّرانِ `latest_build` الموحّدَ وحدَه، والقارئُ
///      يُفضّلُ حقلَ المنصّةِ — فرقمُ البناءِ الذي يَكتبُه الأدمنُ **لا يَقرؤه
///      أحد**. والموحّدُ نفسُه هو العطلُ الأصليُّ: ضُبط مرّةً على رقمِ iOS
///      فرأى كلُّ مختبري أندرويد — وهم على أحدثِ نسخة — مطالبةً إجباريّةً
///      زائفةً لأسابيع.
///
///   ٢) فصارَ المحرّرانِ يَكتبانِ حقلَي المنصّة — و**الصندوقُ الفارغُ يُكتَبُ
///      صفراً** (`int.tryParse('') ?? 0`، `parseInt('') || 0`). والقارئُ كان
///      `(d[platformField] ?? d['latest_build'])`: والصفرُ **ليس** `null`،
///      فيُفضَّلُ على الموحّد، و`currentBuild >= 0` صحيحٌ أبداً — فالمطالبةُ
///      تَموتُ لتلك المنصّةِ **بصمت**، والمفتاحُ والمفتاحُ الإجباريُّ
///      يَبدوانِ عاملَين. ولا بناءَ رقمُه صفرٌ، و«الإطفاءُ» له مفتاحُه
///      (`enabled: false`) — فالصفرُ غيابٌ لا قرار. وهذا هو خلافُ
///      `amounts.js` المقصود: صفرُ ريالٍ قرارٌ، وصفرُ بناءٍ حقلٌ لم يُضبَط
///      (نفسُ منطقِ `slots.js`: صفرُ ساعاتٍ غياب).
///
/// والنوعُ ثالثُ الأخطار: الحقلانِ موجودانِ في الإنتاج لأنّ أحداً **ضبطهما
/// بيدِه** في الكونسول، وقيمةٌ تُكتَبُ هناك قد تكون **نصّاً**. وكان القارئُ
/// `as num?` — ونصٌّ يَرمي `TypeError`، والـ`catch` المحيطُ «صامتٌ» عمداً،
/// فتَموتُ البوّابةُ للمنصّتَين معاً بلا أثرٍ في أيِّ مكان. نفسُ قصّةِ
/// `promo_codes.expiry` بنوعَيها: القراءةُ تَتسامحُ مع النوعَين، لأنّ إصلاحَ
/// الكاتبِ وحدَه لا يُغيّرُ مستنداً قائماً.
library;

/// رقمُ بناءٍ منشورٍ من مستندِ الإعداد، أو `null` إن لم يُضبَط.
///
/// يَقبلُ الرقمَ والنصَّ (مستنداتُ الكونسولِ اليدويّة)، ويَعدُّ الصفرَ
/// والسالبَ والفارغَ وغيرَ الرقميِّ **غياباً** — فالفارغُ يَسقطُ إلى
/// الاحتياطيِّ بدلَ أن يُطفئَ البوّابة.
int? publishedBuild(Object? v) {
  if (v is num) {
    final n = v.toInt();
    return n > 0 ? n : null;
  }
  if (v is String) {
    final n = int.tryParse(v.trim());
    return (n != null && n > 0) ? n : null;
  }
  return null;
}

/// أحدثُ بناءٍ منشورٍ لهذه المنصّة: حقلُها، فالموحّدُ، فلا بوّابة (`null`).
///
/// الترتيبُ هو القرار، وعكسُه يُعيدُ عطلَ 2026-08-31 (رقمُ iOS يُطالبُ
/// أندرويد). والسقوطُ إلى الموحّدِ باقٍ **للمستنداتِ القديمةِ وحدَها**: لا
/// محرّرَ يَكتبُه.
int? latestBuildFor(Map<String, dynamic> d, {required bool isIos}) =>
    publishedBuild(d[isIos ? 'latest_build_ios' : 'latest_build_android']) ??
    publishedBuild(d['latest_build']);
