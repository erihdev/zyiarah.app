/// **نقاطُ «قطرات زيارة» — سعرُ الصرفِ في موضعٍ واحد.**
///
/// كان `50` مكتوباً بيدٍ في خمسةِ مواضعَ: شرطُ الخادمِ الأدنى، وقِسمةُ الخادمِ
/// (`pointsToRedeem / 50.0`)، وشرطُ الزرِّ في الشاشة، وتقريبُها لأقربِ مضاعَف،
/// وشريطُ التقدّمِ (`50 - _qatratPoints`). وهو شكلُ قصّةِ الضريبةِ نفسُها
/// (٢٧ موضعاً، ٥٪ ← ١٥٪، وموضعٌ منسيٌّ يُنتج رقماً خاطئاً **بصمت**).
///
/// والأخطرُ أنّ الشاشةَ كانت تَحسبُ المبلغَ المعروضَ للعميلةِ **بنفسِها**
/// (`earned = toRedeem / 50.0`) وتُهملُ `newBalance`/`newPoints` اللذَين
/// يُعيدُهما الخادم: فلو تَباعدَ الرقمان يوماً، تُبشّرُ العميلةَ بمبلغٍ لم
/// يُودَع. الشاشةُ الآن تَقرأُ ما أودعَه الخادمُ فعلاً.
///
/// المنحُ في المقابلِ ليس هنا: نقطةٌ لكلِّ ريالٍ من الطلبِ المكتمل
/// (`Math.round(amount)` في `onOrderRewards`) — سؤالٌ آخرُ ومكانُه الخادم.
library;

/// نقاطٌ لكلِّ ريالٍ عند الاستبدال (٥٠ نقطة = ١ ر.س).
const int kQatratPerSar = 50;

/// أقلُّ ما يُستبدَل.
const int kQatratRedeemMin = kQatratPerSar;

/// أكبرُ مضاعَفٍ قابلٍ للاستبدالِ من [points] (صفرٌ إن لم يَبلغ الحدَّ).
int qatratRedeemable(int points) =>
    points < kQatratRedeemMin ? 0 : (points ~/ kQatratPerSar) * kQatratPerSar;

/// ما تبقّى من نقاطٍ للوصولِ إلى أوّلِ استبدال (صفرٌ إن بلغَه).
int qatratToNextRedeem(int points) =>
    points >= kQatratRedeemMin ? 0 : kQatratRedeemMin - points;
