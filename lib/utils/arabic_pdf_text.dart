import 'package:arabic_reshaper/arabic_reshaper.dart';

/// **عربيُّ الـPDF: تشكيلٌ ثمّ ردُّ ما لا يَملكُه الخطّ.**
///
/// حزمةُ `pdf` **لا تُشكّلُ** العربيّةَ بإعداداتِها الافتراضيّة: في
/// `pdf/src/pdf/options.dart` يَكونُ `useBidi = true` و
/// `useArabic = !useBidi` أي **false** — فالمُطبَّقُ على نصٍّ RTL هو
/// `bidi.logicalToVisual` (إعادةُ ترتيبٍ بصريّ) وحدَه، **لا**
/// `arabic.convert` (وصلُ الحروف). ولذلك يَلزمُ `arabic_reshaper` قبلَ
/// التسليمِ إلى `pw.Text`، وهو ما يَفعلُه `zyiarah_pdf_service` في أربعينَ
/// موضعاً — وما **لا** يَفعلُه `pdf_report_util` في أيِّ موضعٍ، فالتقريرُ
/// الماليُّ الرسميُّ يُطبَعُ بحروفٍ **منفصلة**.
///
/// **والنصفُ الثاني أخفى وأسوأ: الخطُّ المُضمَّنُ لا يَملكُ أشكالَ الانفصال.**
/// `arabic_reshaper` يُخرِجُ محارفَ «أشكالِ العرض-ب» (U+FE70–FEFF)، و
/// `Tajawal-Regular.ttf` و`-Bold.ttf` — المُضمَّنانِ في الـPDF — يَملكانِ
/// أشكالَ البداية/الوسط/النهاية و**لا يَملكانِ أشكالَ الانفصالِ الستّةَ
/// والثلاثين** (مُستخرَجٌ بقراءةِ `cmap` وحلِّ معرّفِ الرسمة: `glyph id 0`
/// لكلٍّ منها في الخطَّين، مع وجودِ كلِّ الحروفِ الأساسيّة). وشكلُ الانفصالِ
/// هو ما يَأخذُه حرفٌ لا يَصِلُ جهةً — ومنه:
///   • **أ/ا في أوّلِ الكلمة** (الألفُ لا تَصِلُ ما بعدَها): «الرقم»،
///     «المبلغ»، «الإجمالي» — فتَسقطُ الألفُ.
///   • **ة في آخرِ الكلمةِ بعد غيرِ واصل**: «فاتورة»، «مؤسسة»، «ضريبية».
///   • **ر/ز/د/ذ/و في آخرِ الكلمةِ بعد غيرِ واصل**، وكلُّ كلمةٍ من حرفٍ واحد.
/// ورسمةٌ مفقودةٌ في PDF تُطبَعُ **لا شيئاً** (`.notdef`) — فالفاتورةُ
/// الضريبيّةُ والعقدُ الموقَّعُ كانا يُطبَعانِ ناقصَي حروف.
///
/// والعلاجُ أنّ شكلَ الانفصالِ **هو** رسمةُ الحرفِ الأساسيّ بصريّاً، فيُردُّ
/// إليه. و`test/arabic_pdf_text_test.dart` **يَشتقُّ** الفجوةَ من الخطِّ
/// المُضمَّنِ نفسِه: كلُّ شكلٍ يَرمي إليه المُشكِّلُ إمّا في الخطِّ أو في
/// هذه الخريطة، ولا مُدخَلَ في الخريطةِ لشكلٍ يَملكُه الخطّ. فلو استُبدلَ
/// الخطُّ بآخرَ كاملٍ سقطَ الفحصُ ليُراجَعَ لا ليَبقى.

/// شكلُ الانفصالِ ← الحرفُ الأساسيّ (ستّةٌ وثلاثون، مُشتَقّةٌ من فجوةِ الخطّ).
const Map<int, int> kPdfIsolatedFallback = <int, int>{
  0xFE80: 0x0621, // ء
  0xFE81: 0x0622, // آ
  0xFE83: 0x0623, // أ
  0xFE85: 0x0624, // ؤ
  0xFE87: 0x0625, // إ
  0xFE89: 0x0626, // ئ
  0xFE8D: 0x0627, // ا
  0xFE8F: 0x0628, // ب
  0xFE93: 0x0629, // ة
  0xFE95: 0x062A, // ت
  0xFE99: 0x062B, // ث
  0xFE9D: 0x062C, // ج
  0xFEA1: 0x062D, // ح
  0xFEA5: 0x062E, // خ
  0xFEA9: 0x062F, // د
  0xFEAB: 0x0630, // ذ
  0xFEAD: 0x0631, // ر
  0xFEAF: 0x0632, // ز
  0xFEB1: 0x0633, // س
  0xFEB5: 0x0634, // ش
  0xFEB9: 0x0635, // ص
  0xFEBD: 0x0636, // ض
  0xFEC1: 0x0637, // ط
  0xFEC5: 0x0638, // ظ
  0xFEC9: 0x0639, // ع
  0xFECD: 0x063A, // غ
  0xFED1: 0x0641, // ف
  0xFED5: 0x0642, // ق
  0xFED9: 0x0643, // ك
  0xFEDD: 0x0644, // ل
  0xFEE1: 0x0645, // م
  0xFEE5: 0x0646, // ن
  0xFEE9: 0x0647, // ه
  0xFEED: 0x0648, // و
  0xFEEF: 0x0649, // ى
  0xFEF1: 0x064A, // ي
};

/// نصٌّ عربيٌّ جاهزٌ لحزمةِ `pdf`: مُشكَّلٌ، وبلا رسمةٍ مفقودة.
///
/// **البوّابةُ الوحيدةُ** إلى `pw.Text` في المشروع — مسارا الـPDF كلاهما
/// يَمُرُّ بها، فلا مسارَ يَبقى بحروفٍ منفصلةٍ ولا بحروفٍ ساقطة.
String pdfArabic(String input) {
  if (input.isEmpty) return input;
  final reshaped = ArabicReshaper().reshape(input);
  final out = StringBuffer();
  for (final cp in reshaped.codeUnits) {
    out.writeCharCode(kPdfIsolatedFallback[cp] ?? cp);
  }
  return out.toString();
}
