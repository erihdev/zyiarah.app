/// مراحلُ حياة الطلب فيما يخصّ **إسناد السائق** — مصدرٌ واحد لمجموعتين كانتا
/// مكتوبتين بأيديهما في شاشة تفاصيل الطلب وفي `functions/index.js`.
///
/// القسمة مُحكمة ولا تتداخل، وعليها يقوم حارسُ الخادم:
///
///   * [kPreDispatchStatuses] — طلبٌ **لم يُسنَد بعد**: إسنادُه الابتدائي يمرّ
///     عبر `approveAndAssignOrder` (أهليّةٌ كاملة + فحصُ تعارضٍ ذرّي).
///   * [kActiveAssignedStatuses] — طلبٌ **يحمل سائقاً** وما زال نشطاً: إعادةُ
///     جدولته أو إسنادِه تمرّ عبر `rescheduleAssignedOrder`.
///
/// و`assigned` في المجموعتين بقصد: الفارق هو وجود `driver_id` لا الحالة وحدها،
/// فطلبٌ `assigned` بلا سائق (يكتبه مسارٌ قديم) ما زال إسناداً ابتدائياً.
///
/// **لمَ وُجد هذا الملفّ:** كان فرعٌ متبقٍّ في الشاشة يكتب `driver_id` إلى
/// Firestore مباشرةً لكلّ حالةٍ لا يقبلها الخادم — والقواعد تمنح
/// `isOrdersManager()` تحديثاً كاملاً فتمرّ الكتابة. فيتجاوز الإسنادُ فحصَ
/// الأهليّة بأكمله، ومستندُ سائقٍ بلا حساب دخول يُخفي الطلب المدفوع عن الجميع
/// (`firestore.rules` وتطبيق السائق يربطان الرؤية بـ`auth.uid == driver_id`).
/// القائمةُ تعرض كلَّ سائقٍ نشطٍ **بقصد** — «القائمة للعرض، والخادم هو الحارس»
/// — وهذا الفرع كان ينقض الشقّ الثاني من القاعدة.
library;

import 'ksa_instant.dart';

/// حالاتُ ما قبل الإسناد — إسنادٌ ابتدائيّ عبر `approveAndAssignOrder`.
const Set<String> kPreDispatchStatuses = {
  'pending',
  'under_review',
  'awaiting_payment',
  'assigned',
};

/// حالاتٌ نشطة يحمل فيها الطلب سائقاً — عبر `rescheduleAssignedOrder`.
const Set<String> kActiveAssignedStatuses = {
  'scheduled',
  'assigned',
  'accepted',
  'on_the_way',
  'in_progress',
};

/// نفسُها قائمةً، لأنّ `whereIn` في Firestore **تَعدادٌ موجَبٌ لا بُدّ منه**
/// (لا «ليس في هذه المجموعة»). فهي اشتقاقٌ لا نسخةٌ ثانية: حالةٌ تُضافُ إلى
/// دورةِ الحياةِ تَبلغُ كلَّ استعلامٍ من تلقائها.
///
/// **سببُ وجودِها:** `DriverSchedule.activeStatuses` اشتقَّتها لنفسِها
/// بتعليقٍ يَقولُ إنّ الاشتقاقَ هو ما يَمنعُ «سقوطَ مهمّةٍ عن هاتفِ السائقِ
/// بصمتٍ» — ثمّ كتبَت لوحةُ السائقِ ولوحةُ العميلةِ الخمسةَ **إنلاين**،
/// فكانت شاشةُ مهامِّه تَلتقطُ حالةً جديدةً ولوحتُه لا.
final List<String> kActiveAssignedStatusList =
    kActiveAssignedStatuses.toList(growable: false);

/// **لا سائقَ لطلبٍ غيرِ مدفوع.**
///
/// القاعدةُ مُنفَّذةٌ في أربعةِ مساراتٍ خادميّة — `onOrderWritten` لا يُسنِدُ
/// إلّا على **انقلابِ** `is_paid`، وكتلتا `sweepUnassignedPaidOrders` تتخطّيانِ
/// `is_paid !== true`، و`capacity.countBookings` تتخطّاه فلا يَستهلكُ سعة،
/// و`cancelStaleUnpaidOrders` تُلغيه بعد ثلاثين دقيقة — وكانت **غائبةً عن
/// `approveAndAssignOrder` وحدَه**، وهو المسارُ الذي يَنقُرُه الأدمنُ من
/// سطحَين (شاشةُ تفاصيلِ الطلب، وقائمةُ إجراءاتِ صفِّ لوحةِ الويب). شكلُ
/// `isAssignableDriver` بعينِه: مُنفَّذةٌ في اثنَين من أربعة، والمكشوفُ هو ما
/// يُنقَر.
///
/// وإسنادُ سائقٍ لطلبٍ غيرِ مدفوعٍ ثلاثُ نتائج:
///
///   * **(أ) يَخرجُ من مكنسةِ الإلغاء إلى الأبد.** الإسنادُ يَكتبُ
///     `status: 'scheduled'`، و`cancelStaleUnpaidOrders` تَستعلمُ
///     `status == 'pending'` وحدَها — فطلبٌ غيرُ مدفوعٍ أُسنِدَ **لا يُلغى
///     أبداً**: يَبقى مجدولاً بسائقٍ بلا ريال.
///   * **(ب) يَشغلُ السائقَ ولا يَستهلكُ سعة.** `scheduled` داخلَ
///     `slots.CONFLICT_STATUSES` فالمُسنِدُ يَرى السائقَ مشغولاً، و
///     `countBookings` تتخطّى غيرَ المدفوعِ فالسعةُ تَرى الساعةَ حرّة —
///     فتُعرَضُ على عميلةٍ تَدفعُ ثمّ لا يُوجَدُ سائقٌ حرٌّ فتَعلقُ حتى
///     الاستردادِ الآلي. وهي الحادثةُ المسجَّلةُ بنصِّها: «يومٌ ظهرَ متاحاً،
///     دُفِع، فلم يُوجَد سائقٌ مؤهَّل، فعلِقَ الطلبُ حتى الاسترداد الآلي».
///   * **(ج) يُرسَلُ السائقُ ويُذكَّرُ العميلُ.** شرطُ
///     `remindClientsUpcomingAppointments` هو
///     `realAppointment = is_paid === true || driverAssigned`، و
///     `driverAssigned` يَكفيه `status === 'scheduled'` — فتَصِلُها «فريقنا في
///     الطريق إليكِ» لخدمةٍ لم تُدفَع.
///
/// و`pending` **بلا دفعٍ هي الحالةُ الطبيعيّةُ قبلَ الدفع** لكلِّ طلبِ خدمة
/// (الشاشةُ تُنشئُ `status: 'pending'` و`is_paid: false` ثمّ يَقلبُ الـwebhook
/// العلَم)، فالطلبُ يَظهرُ في «رادار الطلبات الجديدة» ثوانيَ بعدَ النقرِ على
/// الدفعِ وقبلَ وصولِه — وتمارا تَستغرقُ ساعات. فالنافذةُ ليست نظريّة.
///
/// القراءةُ `!= true` بقصد: الحقلُ الغائبُ أو التالفُ يُقرأُ **غيرَ مدفوع**،
/// وهو الاتّجاهُ المحافظ، وهو حرفيّاً ما تَقرؤه المساراتُ الخادميّةُ الأربعة.
bool orderPaidForDispatch(Object? isPaid) => isPaid == true;

/// سببُ الرفضِ، بصياغةٍ واحدةٍ للسطحَين — كلا الجمهورَين هو الأدمن، فاختلافُ
/// النصِّ بين سطحَين لقرارٍ واحدٍ هو ما يُنتجُ هذا النوعَ من العطل.
const String kUnpaidDispatchRefusal =
    'لا يمكن إسناد سائق لطلب غير مدفوع — انتظر تأكيد الدفع';

/// **لا موعدَ في الماضي.**
///
/// أربعةُ مواضعَ تَكتبُ موعدَ الخدمةِ — نداءا `approveAndAssignOrder` و
/// `rescheduleAssignedOrder`، وفرعا الكتابةِ المباشرةِ في شاشةِ تفاصيلِ الطلبِ
/// وفي صفحةِ طلباتِ اللوحة — وكانت الأربعةُ تَقبلُ أيَّ تاريخ: الخادمُ
/// يَفحصُ `isNaN(parsedStart.getTime())` وحدَه («موعد غير صالح»)، و
/// `firestore.rules` **صفرُ ذكرٍ** لـ`service_date`.
///
/// **والمُدخَلاتُ الثلاثةُ تُجيزُ الماضيَ كذلك**: حقلا `datetime-local` في
/// اللوحةِ بلا `min`، ومُنتقي الدارتِ بـ`firstDate: DateTime.now()
/// .subtract(const Duration(days: 1))` — أي **أمس** صريحاً.
///
/// **والقاعدةُ مُنفَّذةٌ في السطحَين على كلِّ موعدٍ آخر**، وهذا ما يَجعلُه
/// إكمالاً لا اختراعاً: الدارتُ يَحدُّ مُنتقياتِ البثِّ والكوبونِ وجدولِ
/// المنطقةِ بـ`DateTime.now()`، واللوحةُ تَحدُّ موعدَ البثِّ بـ
/// `min={minScheduleValue()}` — فالمتخلّفُ هو موعدُ الخدمةِ وحدَه.
///
/// **وما يَخرُجُ عليه موعدٌ ماضٍ، مقيساً من الشفرةِ لا مظنوناً:**
///
///   * **مكنسةُ الطلبِ المدفوعِ بلا سائق** تَستعلمُ
///     `service_date >= now − ١٣س` — فطلبٌ مدفوعٌ بتاريخٍ أقدمَ **لا يُسنَدُ
///     آليّاً أبداً**.
///   * **والاستردادُ الآليُّ** (`autoResolveUnfulfilledPaidOrder`) نافذتُه
///     `now − ٢٤س .. now − ١س` — فلا يُستردُّ أيضاً: **مالٌ مقبوضٌ، ولا خدمةَ،
///     ولا استردادَ، ولا تنبيهَ**، وهي الجملةُ التي وُجد ذلك المحرّكُ لإلغائها.
///   * **والتذكيرُ** (`remindClientsUpcomingAppointments`) نافذتُه
///     `now .. now + ٢٤س` — فلا تُذكَّرُ العميلة.
///
/// **ونتيجتانِ سالبتانِ تُسجَّلانِ كما هما:** السائقُ **يَراه** (بثُّ لوحتِه
/// `whereIn` على الحالةِ بلا نافذةِ تاريخٍ، مجموعاً بـ`booking_date`) فقد
/// تُنفَّذُ الخدمةُ فعلاً؛ و`capacity.countBookings` تَعُدُّه في **يومِه
/// الماضي** (تَقرأُ حقلَي الحجزِ، وكلا النداءَين يَكتبُهما صحيحَين) — عَدٌّ
/// بلا معنًى لا عَدٌّ خاطئ، فيومٌ مضى لا يُحجَزُ أصلاً.
///
/// **والعميلُ لا يَبلغُه هذا المسلك**: أشرطةُ الحجزِ الثلاثةُ ومُنتقي الخانةِ
/// كلُّها تَبدأُ من **الغد** (`Duration(days: i + 1)`). فالتعرّضُ إداريٌّ،
/// وخطأُ مُشغِّلٍ لا تلاعب: سنةٌ أو شهرٌ مُخطَأٌ في `datetime-local`.
///
/// **والحدُّ بدايةُ يومِ الرياضِ لا «ليس قبلَ الآن»**، لثلاثةِ أسباب: دقّةُ
/// مُنتقي التاريخِ يومٌ فحدٌّ أدقُّ منه لا يُنفَّذُ في الواجهة؛ وساعةٌ مضت من
/// اليومِ نفسِه موعدٌ مشروعٌ يُسجّلُه الأدمنُ لزيارةٍ تأخّرَ إدخالُها؛ وتلك
/// الساعةُ **داخلَ** نافذةِ الـ١٣ ساعةً فتَبقى قابلةً للاستعادة.
///
/// ويومُ الرياضِ لا يومُ الجهاز: الخادمُ يَقرأُ النصَّ الساذجَ بتوقيتِ الرياضِ
/// (`parseKsaIso`)، فحدٌّ بيومِ المتصفّحِ يَرفضُ موعداً مشروعاً أو يُجيزُ
/// ماضياً بحسبِ المنطقة. و[now] للفحصِ وحدَه — لا موضعَ نداءٍ يُمرّرُه،
/// فالرياضيّةُ **غيرُ قابلةٍ للنسيان** في موضعِ النداء.
bool serviceDateAllowed(DateTime chosenWall, {DateTime? now}) =>
    !chosenWall.isBefore(ksaTodayWall(now));

/// سببُ الرفضِ، بصياغةٍ واحدةٍ للسطحَين وللخادم — كلا الجمهورَين هو الأدمن.
const String kPastServiceDateRefusal =
    'لا يمكن ضبط موعد في الماضي — اختر اليوم أو تاريخاً بعده';
