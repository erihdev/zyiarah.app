/// حظرُ الحساب: **قاعدةٌ واحدةٌ وجملةٌ واحدة.**
///
/// العلمان يَعنيانِ القرارَ نفسَه، ويُكتبانِ من سطحَين:
///   • `status == 'banned'` — تَكتبُه شاشةُ المستخدمينَ في تطبيقِ الإدارةِ
///     وصفحةُ المستخدمينَ في لوحةِ الويب.
///   • `is_blocked == true` — حظرٌ قديمٌ من المدير العامِّ أو الكونسول.
/// و`firestore.rules` تَحصُرُ الاثنَين بالمدير العامّ، فلا يَكتبُهما عميلٌ
/// أبداً — ومن ثَمّ فالرسالةُ صادقةٌ دائماً حين تَظهر.
///
/// **ولماذا جملةٌ واحدة:** كان حظرُ الحسابِ يُنهي الجلسةَ **بصمتٍ تامّ** —
/// `user_provider` يَرى العلمَ فيُنادي `signOut()` ويَرجعُ، فتَرتدُّ المستخدمةُ
/// إلى شاشةِ الترحيبِ بلا كلمة. و`debugPrint` لا يُجمَع. فهي تَقرأُ الارتدادَ
/// «كلمةُ مرورٍ خاطئة»، فتُعيدُ المحاولةَ ثمّ تُراسِلُ الدعم — وهو **بعينِه**
/// التعليلُ المسجَّلُ لبوّابةِ دخولِ لوحةِ الويب، التي تَرفضُ برسالةٍ تُسمّي
/// السبب. فالقاعدةُ كانت مُنفَّذةً في اللوحةِ (سطحُ الموظّفين) وغائبةً عن
/// التطبيق (سطحُ العميلة).
///
/// **والنصُّ محيَّدُ الجنسِ بقصد:** الأدوارَ الثلاثةَ كلَّها تَقرؤه (شاشةُ
/// الترحيبِ هي ما يَراه كلُّ خارجٍ من الجلسة)، وقرارُ هذا المستودعِ في مثلِه
/// تحييدٌ لا تأنيث — كما في `global_error_handler` ومُنتقي الموقعِ ونصِّ
/// الإحالة.
library;

/// هل هذا المستندُ لحسابٍ محظور؟ غيابُ المستندِ ليس حظراً.
bool accountIsBlocked(Map<String, dynamic>? data) {
  if (data == null) return false;
  return data['is_blocked'] == true || data['status'] == 'banned';
}

