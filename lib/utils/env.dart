import 'package:flutter_dotenv/flutter_dotenv.dart';

/// **مفتاحُ نشرٍ من `.env`، وغيابُه تعطّلٌ لا انهيار.**
///
/// `.env` أصلٌ مُعلَنٌ في `pubspec.yaml` يَحملُ المفاتيحَ **القابلةَ للنشر**
/// وحدَها (رمزُ Mapbox، مفتاحُ ميسر العامّ، معرّفُ خدمةِ Samsung Pay) —
/// ولا سِرَّ فيه إطلاقاً، فهو يُحزَمُ داخلَ التطبيقِ وأيُّ قارئٍ يَستخرجُه.
///
/// والسببُ في وجودِ هذه الدالّة أنّ `dotenv.env` **يَرمي** `NotInitializedError`
/// متى لم يَنجحْ `load()` — لا يُعيدُ خريطةً فارغة. فمواضعُ القراءةِ العشرةُ
/// كلُّها تَكتبُ `?? ''` أي أنّها تَقصدُ «مفتاحٌ غائبٌ ⇒ تعطّلُ الميزة»،
/// ولا تَبلغُ `??` أصلاً لأنّ الرميَ يَسبقُها. فهذه الدالّةُ تُحقّقُ ما
/// تَقصدُه تلك المواضعُ فعلاً: غيابُ الملفِّ أو فشلُ تحميلِه يُساوي مفتاحاً
/// فارغاً، فيَنطفئُ خيارُ البطاقةِ وApple Pay (`moyasarReady`) وتَعجزُ
/// الخريطةُ عن الرسم — وهو تعطّلٌ مرئيٌّ مقصود، لا شاشةٌ بيضاء.
String envOrEmpty(String key) {
  if (!dotenv.isInitialized) return '';
  return dotenv.env[key] ?? '';
}
