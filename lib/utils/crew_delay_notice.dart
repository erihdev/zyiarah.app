/// **عميلةٌ دَفعت، وفاتَ موعدُها، ولا فريق — ولم يكن يُقالُ لها شيء (2026-10-05).**
///
/// `sweepUnassignedPaidOrders` يَجري كلَّ خمسِ دقائق: يُسندُ ما بَقي بلا سائق،
/// وإن فاتَ موعدُ البدءِ بساعةٍ ولم يُسنَد **يُنبّهُ الإدارةَ مرّةً** ويُواصل
/// المحاولةَ حتى نهايةِ النافذة، فإن فَشل استردَّ المبلغَ آليّاً
/// (`autoResolveUnfulfilledPaidOrder`). والعميلةُ في هذا كلِّه لا تَسمعُ شيئاً:
///
///   • تَلقّت قبلَ ساعتَين «**فريقنا في الطريق إليكِ** 🚗» — وعدٌ عن فريقٍ لا
///     وجودَ له، لأنّ تذكيرَ الساعتَين كان يُرسَلُ لطلبٍ مدفوعٍ ولو بلا سائقٍ
///     إطلاقاً (`realAppointment` يَكفيه `is_paid === true`).
///   • ثمّ يَمضي الوقتُ ولا يَأتي أحد، وبطاقةُ الطلبِ تَقول «قيد الانتظار» —
///     وتَحتها «**انتهى الموعد**»، فتَقرأُ أنّ خدمتَها انتهت وهي لم تَبدأ.
///   • ولا إشعارَ حتى نهايةِ النافذة: باقةُ ١٢ ساعةً = اثنتا عشرةَ ساعةَ صمت.
///
/// فصارَ للخادمِ دفعةٌ تَخصُّها على علمٍ خاصٍّ بها
/// (`client_stranded_notified`، لا `stranded_alerted` الإداريّ — علمٌ واحدٌ
/// لجمهورَين يَجعلُ أسبقَهما يُسكِتُ الآخر، وهو عطلٌ مسجَّلٌ حرفيّاً في هذا
/// المستودع)، وهذه القاعدةُ هي نظيرُها على البطاقةِ التي تَنظرُ إليها فعلاً.
///
/// **ولا تُقيَّدُ بنهايةِ النافذةِ عن قصد.** لو قُيّدت، ثمّ فَشل الاستردادُ
/// الآليُّ (أحدُ فروعِ `_failAndEscalate`: `gateway_error`/`no_payment_id`/…)
/// لبَقي الطلبُ `pending` للأبدِ **بلا إشعارٍ ولا سطرٍ على البطاقة** — أسوأُ
/// مما كان. فالإشعارُ يَبقى ما بَقي الطلبُ معلّقاً، ويَزولُ من نفسِه حين
/// يَنجحُ الاستردادُ (تَصيرُ الحالةُ `cancelled`).
library;

/// مهلةُ ما بعدَ موعدِ البدءِ قبلَ أن يُقالَ شيء — **نفسُ عتبةِ الخادم**
/// (`start < now - 60 * 60 * 1000` في `sweepUnassignedPaidOrders`). لو
/// افترقَ الرقمان لرأت العميلةُ سطراً على البطاقةِ بلا إشعارٍ يُفسّره، أو
/// العكس.
const Duration kCrewDelayGrace = Duration(hours: 1);

/// الحالةُ الوحيدةُ التي يَعمَلُ عليها مسحُ الإسنادِ الخادميّ — فلا نَقولُ
/// «نعمل عليه» عن طلبٍ لا يَعملُ عليه أحد.
const String kCrewDelayStatus = 'pending';

/// هل يَستحقُّ هذا الطلبُ سطرَ «تأخّر إسنادُ فريقكِ»؟
///
/// الشروطُ مرآةُ الخادمِ حرفاً: مدفوعٌ، بلا سائق، حالتُه [kCrewDelayStatus]،
/// وله موعدٌ فاتَ بـ[kCrewDelayGrace].
///
/// [appointment] يُمرَّرُ من `service_date` حصراً — وهو شرطُ الخادمِ نفسُه
/// (`if (!d.service_date) continue`). البديلُ `booking_date` بلا خانةِ وقتٍ
/// يُنتجُ منتصفَ الليل، فيُظهرُ السطرَ في الواحدةِ صباحاً عن موعدٍ لم يَحِن.
bool crewDelayNotice({
  required bool isPaid,
  required String? driverId,
  required String status,
  required DateTime? appointment,
  required DateTime now,
}) {
  if (!isPaid) return false;
  if (driverId != null && driverId.isNotEmpty) return false;
  if (status != kCrewDelayStatus) return false;
  if (appointment == null) return false;
  return now.isAfter(appointment.add(kCrewDelayGrace));
}

/// النصُّ المعروض — صادقٌ بما نَعرفُه: نُحاولُ الآن، وإن تعذّر أُعيد المبلغُ
/// كاملاً تلقائيّاً (وهو ما يَفعلُه الخادمُ فعلاً عند نهايةِ النافذة).
const String kCrewDelayMessage =
    'تأخّر إسناد فريقكِ ونحن نعمل عليه الآن. وإن تعذّر علينا تنفيذه '
    'أُعيد المبلغ كاملاً تلقائيّاً.';
