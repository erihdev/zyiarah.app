/// «وماذا يَحدثُ للخدمةِ إن استردَدتُ المال؟» — سؤالٌ لم يَكن يُجابُ في
/// اللحظةِ التي لا رجعةَ فيها، على ثلاثةِ أسطح.
///
/// حوارُ تأكيدِ عمليّاتِ البوّابةِ يَقولُ شيئاً واحداً — «هل أنت متأكد من
/// تنفيذ «استرداد المبلغ»؟ لا يمكن التراجع» — في `_moyasarOperation` و
/// `_bnplRefundOperation` بتطبيقِ الإدارةِ و`handleBnplRefund` بلوحةِ الويب.
/// وهو نفسُ الشكلِ الذي استُبدِلَ في **الاتّجاهِ المعاكس**: حوارُ الإلغاءِ كان
/// سطراً واحداً كذلك، فصارَ يَقولُ إلى أين يَذهبُ المال
/// (`cancel_refund_notice.dart`، ثلاثةُ أسطح). والاتّجاهُ الآخرُ تُرِك —
/// **وهو الأحدُّ**، لأنّ ما لا يُقال فيه ليس مصيرَ المالِ بل مصيرَ الخدمة.
///
/// **ما تَفعلُه البوّابةُ فعلاً:** `moyasarRefundPayment` يَكتبُ
/// `payment_status: "refunded"` و`is_paid: false`، و`moyasarVoidPayment`
/// يَكتبُ `"voided"` و`is_paid: false`، ومسارا التقسيطِ يَكتبانِ
/// `"refunded"` و`is_paid: false` و`refunded: true` — **وأربعتُها لا تَمَسُّ
/// `status` إطلاقاً**. وتعليقُ مسارِ ميسر يَقولُها صريحاً: «والحالةُ النشطةُ
/// تُبقيه في لوحةِ السائق». فالنتيجةُ:
///
///   * طلبٌ مفتوحٌ **يَحملُ سائقاً** ⇒ يَبقى على هاتفِه، فيَذهبُ الفريقُ
///     وينفّذُ الخدمةَ بلا مقابل. وبطاقةُ العميلةِ تَبقى «مجدول» بزرِّ تتبّعٍ
///     بينما وصلَتها دفعةُ «تم استرداد مبلغك 💳» — إشارتانِ متناقضتان.
///   * طلبٌ مفتوحٌ **بلا سائق** ⇒ لا فريقَ يَذهب (الإسنادُ يَشترطُ الدفعَ في
///     مَوضعِ الكتابةِ نفسِه)، لكنّه يَبقى معلّقاً: مكنسةُ الإلغاءِ تَقرأُ
///     `pending` وحدَها، فحالةٌ أخرى تَبقى في طابورِ ما يَنتظرُ قراراً.
///   * طلبٌ **منتهٍ** (`completed`/`cancelled`/…) ⇒ لا خدمةَ قادمةً أصلاً،
///     فلا جملةَ عن الفريق.
///
/// و**الاستردادُ الجزئيُّ** (مبلغٌ أقلُّ من المدفوع، وميسر وحدَها تَقبلُه)
/// يَكتبُ `is_paid: false` كذلك — فالطلبُ يُقرأُ **غيرَ مدفوعٍ بالكامل** في
/// كلِّ مكان: عدُّ السعةِ يَتخطّاه، والتذكيرُ لا يَصِلُ، والجوائزُ لا تُمنَح.
/// وذاك أثرٌ يُقالُ قبلَ الضغطِ لا يُكتشَفُ بعدَه.
library;

import 'order_activity.dart';

/// عمليّةُ البوّابةِ التي تُعيدُ المالَ أو تُحرّرُه.
///
/// `capture` ليست هنا بقصد: هي الاتّجاهُ المعاكس (تَأخذُ المالَ وتَكتبُ
/// `is_paid: true`)، فلا جملةَ تَحذيرٍ لها.
enum RefundOp {
  /// استردادُ مبلغٍ مقبوض.
  refund,

  /// إلغاءُ تفويضٍ لم يُقبَض.
  voidAuth,
}

/// أثرُ العمليّةِ على **الخدمة** — وهو ما كان غائباً عن الحوار.
enum RefundServiceImpact {
  /// مفتوحٌ ويَحملُ سائقاً: الفريقُ يَذهبُ ما لم يُلغَ الطلبُ أيضاً.
  crewStillAssigned,

  /// مفتوحٌ بلا سائق: لا فريقَ، لكنّه يَبقى معلّقاً.
  openWithoutCrew,

  /// منتهٍ: لا خدمةَ قادمة.
  serviceEnded,
}

/// القرارُ نقيٌّ كي يُختبَرَ بلا Firebase — والمدخلانِ من مستندِ الطلبِ نفسِه
/// الذي تُرسَمُ منه البطاقة، فلا حالةَ «جارٍ التحميل» هنا.
///
/// «مفتوح» هو [orderIsOpen] بعينِه: المنتهي مجموعةٌ قصيرةٌ ثابتةٌ وما عداه
/// مفتوح — فحالةٌ تُضافُ غداً لا تَسقطُ من التحذير.
RefundServiceImpact refundServiceImpact({
  required String? status,
  required bool hasDriver,
}) {
  if (!orderIsOpen(status)) return RefundServiceImpact.serviceEnded;
  return hasDriver
      ? RefundServiceImpact.crewStillAssigned
      : RefundServiceImpact.openWithoutCrew;
}

/// السطرُ المُلحَقُ بسؤالِ التأكيد — فارغٌ حين لا شيءَ يُقال.
///
/// الجمهورُ الأدمنُ في الأسطحِ الثلاثة، فالصياغةُ واحدةٌ حرفاً بحرف: اختلافُ
/// النصِّ بين سطحَين لقرارٍ واحدٍ هو ما يُنتجُ هذا النوعَ من العطل.
String refundNoticeText({
  required RefundOp op,
  required RefundServiceImpact impact,
  required bool partial,
}) {
  final String verb =
      op == RefundOp.voidAuth ? 'إلغاءُ التفويض' : 'استردادُ المبلغ';
  final List<String> lines = <String>[];
  switch (impact) {
    case RefundServiceImpact.crewStillAssigned:
      lines.add('$verb لا يُلغي الطلب: يبقى بحالته وسائقُه مُسنَداً، '
          'فيذهب الفريق إلى العميلة. ألغِ الطلب أيضاً إن كانت الخدمة '
          'لن تُنفَّذ.');
      break;
    case RefundServiceImpact.openWithoutCrew:
      lines.add('$verb لا يُلغي الطلب: يبقى مفتوحاً بلا سائق ولن يُسنَد له '
          'فريق بعدها (الإسناد يشترط الدفع). ألغِه أيضاً كي لا يبقى '
          'معلّقاً.');
      break;
    case RefundServiceImpact.serviceEnded:
      break;
  }
  if (partial) {
    lines.add('الاسترداد الجزئي يَسِم الطلب غير مدفوع بالكامل، فيخرج من '
        'عدّ السعة والتذكيرات والجوائز.');
  }
  return lines.join(' ');
}
