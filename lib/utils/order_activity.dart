/// «هل الطلبُ ما زال مفتوحاً؟» — مصدرٌ واحدٌ لقسمةٍ كانت مكتوبةً بيدها **ثلاثَ
/// مرّات** على ثلاثِ شاشاتٍ، صحيحةً في واحدةٍ وخاطئةً في اثنتين.
///
/// القاعدةُ **قاعدةٌ لا تعداد**: الحالاتُ المنتهيةُ قليلةٌ وثابتةٌ
/// ([kTerminalOrderStatuses])، وما ليس فيها فالطلبُ مفتوح. وهذا هو الشقُّ الذي
/// يَهمّ: العدّاداتُ الثلاثةُ كُتبت تعداداً للحالاتِ **النشطة**، فكلُّ حالةٍ
/// أُضيفت بعدها سَقطت من العدِّ بصمت — `scheduled` و`accepted` و`on_the_way`
/// و`delivering` كلُّها لاحقةٌ على ذلك التعداد.
///
/// **ما كان يَحدث:**
///
///   * `admin_insights_screen` («طلبات نشطة» في لوحةِ المالك) كانت تَعدُّ من
///     `orders` ثلاثَ حالاتٍ فقط — `pending`/`assigned`/`in_progress` — فطلبٌ
///     مجدولٌ أو مقبولٌ أو سائقُه في الطريق **لا يُعدُّ نشطاً**. ومن
///     `store_orders` كانت تَعدُّ `pending`/`processing`، و**لا أحدَ يَكتبُ
///     أيّاً منهما** على طلبِ متجر: الدورةُ الحقيقيّةُ
///     `awaiting_payment ⇒ under_review ⇒ delivering ⇒ delivered` (قرارُ المالك
///     «لا موافقة قبل الدفع» — `store_service.dart`). فحصّةُ المتجرِ من العدّادِ
///     كانت **صفراً دائماً**، بنيةً لا عَرَضاً.
///
///   * `Dashboard.tsx` (لوحةُ الويب) كانت تَعرضُ بطاقةَ «طلبات بانتظار
///     الموافقة» من `where('status','==','pending')` على `store_orders` —
///     رقمٌ صفريٌّ أبداً، وعنوانٌ يُسمّي خطوةَ موافقةٍ **أُلغيت**. الرقمُ الذي
///     يَحتاجُه المالكُ هو ما يَنتظرُ نقرةً منه: [kStoreNeedsActionStatuses].
///
///   * `orders_list_screen` (تبويبا العميلة) كانت القائمةَ الصحيحةَ — صُحّحت
///     مرّةً حين كان الطلبُ المدفوعُ يَختفي من التبويبين معاً — ومنها أُخذت
///     [kTerminalOrderStatuses] حرفيّاً. لكنّ تعدادَ الطرفَين تَركَ ثقباً
///     كامناً: حالةٌ خارجَ القائمتَين (مثل `out_for_delivery` أو `preparing`،
///     وكلتاهما في خريطةِ إشعاراتِ `notifyClientOnStoreOrderStatus`) تَسقطُ من
///     **التبويبين معاً** فلا تَراها العميلةُ أصلاً. لا كاتبَ لهما اليومَ فهو
///     كامنٌ لا حيّ — والقاعدةُ تُغلقُه بلا تعدادٍ ثالث.
///
/// `refunded` ليست هنا بقصد: هي قيمةُ `payment_status` لا `status`
/// (`functions/index.js` يَكتبُها على ذلك الحقلِ وحدَه)، وإدراجُها هنا كان
/// سيُضيفُ قيمةً لا يَكتبُها شيءٌ — وهو عينُ الخللِ الذي يُصلحُه هذا الملفّ.
library;

/// حالاتٌ **منتهية**: خرج الطلبُ من العمل. مأخوذةٌ حرفيّاً من
/// `historyStatuses` في `orders_list_screen` — الموضعُ الوحيدُ الذي كان صحيحاً.
const Set<String> kTerminalOrderStatuses = {
  'delivered',
  'completed',
  'cancelled',
  'rejected',
};

/// حالاتُ طلبِ المتجرِ التي تَنتظرُ **نقرةً من الإدارة**: المدفوعُ تحت المراجعةِ
/// يَنتظرُ «جاري التوصيل»، والجاريُ توصيلُه يَنتظرُ «تم التسليم» — وهما الزرّان
/// اللذان تَعرضُهما شاشتا الإدارةِ فعلاً. `processing`/`shipped` إرثُ المسارِ
/// القديمِ تُعامَلان نظيرتَيهما (كما في `admin_store_orders_screen`) كي تُعدَّ
/// المستنداتُ القديمةُ أيضاً.
const Set<String> kStoreNeedsActionStatuses = {
  'under_review',
  // دورةُ 2026-10-24: «قيد التجهيز» يَنتظرُ «جاهز»، و«جاهز» يَنتظرُ اختيارَ
  // السائق. و«مع السائق» ليس هنا — السائقُ يُسلِّمُ لا الإدارة.
  'preparing',
  'ready',
  'delivering',
  'processing',
  'shipped',
};

/// طلبٌ مفتوحٌ = حالتُه ليست منتهية. الغائبُ/الفارغُ مفتوحٌ: مستندٌ بلا حالةٍ
/// طلبٌ لم يُنتهَ منه، وعدُّه منتهياً يُخفيه عن المالكِ وعن العميلةِ معاً.
/// سقفُ ما تَستمعُ له شاشةُ «حجوزاتي» للعميلةِ من كلِّ مجموعة (الأحدثُ أوّلاً).
///
/// كان البثُّ **بلا حدٍّ**: `where('client_id')` وحدَها، فكلُّ طلبٍ في عمرِ
/// الحسابِ يُقرَأُ ويُبقى حيّاً في المستمعِ ويُفرَزُ محلّيّاً عند كلِّ تغيُّر.
/// والسقفُ **مع `orderBy('created_at')`** لا بلاه: `limit` وحدَها تُعيدُ N
/// بترتيبِ المعرّفِ لا الأحدث (الدرسُ المسجَّلُ في صندوقِ الإشعارات)، وكلُّ
/// مُنشِئٍ للطلبِ — العميلُ والخادمُ ومولِّدُ زياراتِ العقد — يَكتبُ
/// `created_at`، فلا مستندَ يَسقطُ من الترتيب. والفهرسُ `(client_id,
/// created_at)` قائمٌ للمجموعتَين. والرقمُ واحدٌ هنا كي لا تَفترقَ ملاحظةُ
/// «يُعرَضُ أحدثُ N» عن الاستعلامِ الذي تَصِفُه.
const int kClientOrdersQueryLimit = 200;

bool orderIsOpen(Object? status) {
  final s = (status is String ? status : '${status ?? ''}').trim();
  return !kTerminalOrderStatuses.contains(s);
}

/// طلبُ متجرٍ يَنتظرُ إجراءً إداريّاً.
bool storeOrderNeedsAction(Object? status) {
  final s = (status is String ? status : '${status ?? ''}').trim();
  return kStoreNeedsActionStatuses.contains(s);
}
