import 'package:zyiarah/utils/catalog_number.dart' show normalizeDigits;

/// رقم للمراسلة عبر wa.me: أرقام فقط بصيغة دولية عارية (بلا + ولا 00).
///
/// أرقام العملاء والسائقين تُحفظ محلياً غالباً («05xxxxxxxx» أو «5xxxxxxxx»)
/// بينما wa.me لا يقبل إلا الصيغة الدولية — فيُلحق رمز السعودية 966 بها.
/// يعيد '' حين لا رقم.
String whatsappNumber(String? raw) {
  // **السعوديُّ تُجيبُ عنه القاعدةُ الواحدة.** كانت هذه الدالّةُ مُطبِّعاً
  // **خامساً** بقاعدةٍ أضيق، وثلاثُ صِيَغٍ تُنتجُ عندها رابطاً ميتاً —
  // كشفَها شاهدُ التعليلِ في `test/saudi_mobile_test.dart` لا المراجعة:
  //
  //   • `9660501234567` (مفتاحٌ ومحلّيٌّ بصفر) تَمُرُّ كما هي فيُبنى
  //     `wa.me/9660501234567`، وفيه صفرٌ زائد؛
  //   • والأرقامُ العربيّةُ-الهنديّةُ والفارسيّةُ تُصفّى كلُّها فيَبقى فراغٌ
  //     ⇒ `wa.me/` عارياً.
  //
  // ومَقيسٌ أنّ الباقيَ لم يَتغيّر: ثمانيةٌ وعشرونَ من واحدٍ وثلاثين جواباً
  // متطابقةٌ حرفيّاً، والثلاثةُ المُتغيّرةُ **رابطٌ ميتٌ صارَ عاملاً** — ولا
  // جوابٌ صحيحٌ انقلب. والاحتياطيُّ أدناه يَبقى كما هو: ما ليس سعوديّاً
  // يَمُرُّ بلا أن نُلحِقَ به 966، وهو قرارٌ مشدودٌ في فحصِها.
  final ksa = saudiE164(raw);
  if (ksa != null) return ksa.substring(1);

  if (raw == null) return '';
  var digits = raw.replaceAll(RegExp(r'[^0-9]'), '');
  if (digits.isEmpty) return '';
  if (digits.startsWith('00')) digits = digits.substring(2);
  if (digits.length == 10 && digits.startsWith('05')) {
    return '966${digits.substring(1)}';
  }
  if (digits.length == 9 && digits.startsWith('5')) return '966$digits';
  return digits;
}

/// **رقمُ الجوالِ السعوديُّ: صيغةٌ واحدةٌ، وأربعةُ مُطبِّعينَ كانوا بأربعِ
/// صِيَغ.**
///
/// حقلُ `users/{uid}.phone` كان يُخزَّنُ **كما كُتب**: محرِّرُ التسجيلِ
/// يَتحقّقُ من `^0?5\d{8}$` ثمّ يُمرّرُ النصَّ الخامَّ (`phone: phone`)، وشاشةُ
/// الدفعِ تُعبّئُ المخزَّنَ خامّاً وتَكتبُه خامّاً **بلا أيِّ فحصِ صيغة**،
/// و`createTamaraCheckout` يَفعلُ `startsWith("+") ? raw : "+966" + raw`.
/// فالرقمُ الذي يَبلغُ بوّابةَ التقسيطِ يَتبعُ ما كَتبَته (مَقيسٌ، لا مَظنون):
///
/// | المكتوب | يُقبَلُ في التسجيل | يُرسَلُ إلى تمارا | E.164؟ |
/// |---|---|---|---|
/// | `501234567` | نعم | `+966501234567` | ✓ |
/// | `0501234567` | نعم | `+9660501234567` | ✗ عشرةُ أرقامٍ بعدَ 966 |
/// | `966501234567` | نعم | `+966966501234567` | ✗ 966 مُضاعَفة |
/// | `+966501234567` | نعم | `+966501234567` | ✓ |
/// | `+966 50 123 4567` | نعم | `+966 50 123 4567` | ✗ مسافات |
/// | `00966501234567` | **لا** | — | — |
///
/// **وحيٌّ الآن نصفانِ، ولكلٍّ حدُّه:**
///
/// * **`00966…` لا يُسجَّلُ أصلاً** — فحصُ التسجيلِ `startsWith('966')` وحدَه،
///   فالبادئةُ الدوليّةُ بـ`00` (وهي كيف يُكتَبُ الرقمُ على بطاقةٍ أو في
///   «جهات الاتصال» في الخليج) تُرفَضُ بينما `+966` تُقبَل: **رقمٌ واحدٌ
///   بجوابَين بحسبِ ما كَتبَته**. وهو شكلُ `_phoneToEmail` المحذوفِ بنصِّه في
///   `CLAUDE.md` («one phone number, two different accounts, depending on how
///   she typed it»)، والمُطبِّعُ الصحيحُ الذي يُسمّيه ذلك المدخلُ قائمٌ في
///   `getUserRole` (يُعالِجُ `00966` صراحةً) وفي `whatsappNumber` (تُسقِطُ
///   `00`) — فالناقصُ هو المحرِّرُ الذي يَحرُسُ إنشاءَ الحساب. والرسالةُ
///   قابلةُ العلاجِ («أدخلي رقماً سعودياً يبدأ بـ 05») فتَستطيعُ التعافي.
/// * **وثلاثُ شاشاتٍ تَطلبُ ثلاثَ صِيَغ**: تلميحُ حقلِ التسجيلِ `5XXXXXXXX`،
///   ورسالةُ خطئه «يبدأ بـ **05**»، وتلميحُ بطاقةِ الدفعِ «مثال:
///   `0501234567`» — والصيغةُ التي تَطلبُها الرسالتانِ العربيّتانِ هي بعينِها
///   التي تُنتجُ `+9660501234567`.
///
/// **وكامنٌ نصفٌ ثالث، ويُقالُ بحدِّه**: مسارا تمارا الثلاثةُ كلُّها مشروطةٌ
/// بـ`tamara_enabled` **وافتراضُه `false`**، فالرقمُ المُشوَّهُ لا يَبلغُ
/// البوّابةَ حتى يُشغّلَ المالكُ التقسيطَ — والمفتاحُ صارَ في المحرِّرَين معاً.
///
/// **ونتيجةٌ سالبةٌ تُسجَّلُ كما هي:** لا قارئٍ آخرَ يَنكسِرُ على اختلافِ
/// الصِيَغ — `whatsappNumber` تُعالِجُ الستَّ كلَّها (مَقيسٌ في فحصِها)،
/// و`tel:` يَقبلُ أيَّ شكل، وبحثُ الإدارةِ في السطحَين `contains`/`includes`
/// فيُطابِقُ النواةَ التسعيّة. والمُطبِّعُ الرابعُ — مُنسِّقُ شاشةِ STC —
/// **صحيحٌ وقائمٌ بذاتِه**: تَكتبُ الرقمَ فيه من جديدٍ ولا يُعبَّأُ من
/// `users.phone`، فلم يُلمَس.
///
/// فالقاعدةُ: **نُطبِّعُ ثمّ نتحقّقُ ثمّ نَرفُض** — قرارُ `catalog_number.dart`
/// بعينِه — والصيغةُ القانونيّةُ `05XXXXXXXX` لأنّها ما تَطلبُه الرسالتانِ
/// القائمتانِ، وما يُنتجُه مُنسِّقُ STC، وما تَبدأُ به `whatsappNumber`، وما
/// يَقرؤه السائقُ على بطاقتِه.
///
/// والإصلاحُ على **الكاتبِ والخادمِ معاً**: مستنداتُ الإنتاجِ تَحملُ الصِيَغَ
/// الخمسَ سلفاً، وإصلاحُ الكاتبِ وحدَه لا يُعيدُ كتابةَ ما كُتب — قرارُ
/// احتياطِ `latest_build` و`couponExpiryMs` ولنفسِ السبب.
///
/// يُعيدُ `null` حين لا يَنحلُّ إلى جوّالٍ سعوديّ — و`null` يَعني **غيرَ
/// صالح**، فلا يُبتلَعُ إلى قيمةٍ مُختَرَعة.
String? saudiMobile(String? raw) {
  if (raw == null) return null;
  // `normalizeDigits` مشترَكةٌ لا منسوخة: تُحوّلُ العربيّةَ-الهنديّةَ
  // والفارسيّةَ وتُسقِطُ علاماتِ الاتّجاهِ غيرَ المرئيّةِ — وهي حالةٌ حيّةٌ
  // في هذا المشروع، فالقيمةُ المسجَّلةُ في تعليقِ `support_fab` كانت
  // «+966 53 048 9016» بعلاماتِ U+202D/U+202C.
  var d = normalizeDigits(raw).replaceAll(RegExp(r'[^0-9]'), '');
  if (d.isEmpty) return null;
  // **الفرعانِ حصريّانِ، والترتيبُ بينهما لا يُغيّرُ شيئاً** — مُثبَتٌ
  // باختبارِ قضمٍ عكسَهما فلم يَسقطْ شيء، فلا يُدَّعى غيرُ ذلك. وخطأُ
  // `_phoneToEmail` المحذوفِ كان من شكلٍ آخر: أزالَ `966` **حيث وَردَت**
  // ثمّ صفراً في الأوّلِ **بالتتابُع**، فـ`00966…` صارت `0…` ثمّ `…`
  // ⇒ حسابانِ لرقمٍ واحد. وما يَحمي هنا أنّ الإزالةَ بـ`startsWith` من
  // الأوّلِ لا بالبحثِ في الوسط، وأنّ شرطَ `^5\d{8}$` صارمٌ بعدَها.
  if (d.startsWith('00966')) {
    d = d.substring(5);
  } else if (d.startsWith('966')) {
    d = d.substring(3);
  }
  if (d.startsWith('0')) d = d.substring(1);
  // صارِمٌ لا «آخرُ تسعةِ أرقام»: الأخيرُ يَقبلُ `99999501234567` بقصِّه.
  if (!RegExp(r'^5\d{8}$').hasMatch(d)) return null;
  return '0$d';
}

/// الصيغةُ الدوليّةُ `+9665XXXXXXXX` لبوّاباتِ الدفع، أو `null`.
String? saudiE164(String? raw) {
  final local = saudiMobile(raw);
  return local == null ? null : '+966${local.substring(1)}';
}
