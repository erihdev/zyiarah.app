/// ضريبة القيمة المضافة — المصدر الوحيد للنسبة، ونموذجاها مسمَّيان صريحاً.
///
/// كانت النسبة مكتوبة يدوياً في أكثر من ثلاثين موضعاً بتسعة عشر ملفاً، بصيغ
/// `1.15` و`0.15` و`/ 1.15`. وتغيير نسبة الضريبة حدث فعلاً في السعودية (٥٪ ←
/// ١٥٪ في ٢٠٢٠)، وأي موضع منسيّ في تغيير تالٍ يُنتج فواتير خاطئة **بصمت**.
///
/// والأخطر من التكرار أن في الشفرة **نموذجين** للضريبة، لا يفرّق بينهما إلا
/// تعليقٌ عند موضع الاستخدام:
///
///   أ. الضريبة **تُضاف فوق** أساسٍ غير شامل  → `base * 0.15`
///   ب. الضريبة **تُستخرج من** إجمالٍ شامل    → `gross - gross / 1.15`
///
/// وكلاهما مستعمل وصحيح في موضعه. والخطر أن الاسم لا يقول أيَّهما: في
/// `store_schedule_screen` الحقل `total` **أساس** (تُضاف عليه)، وفي
/// `store_payment_screen` الحقل `total` نفسه **إجمالٌ شامل** (تُستخرج منه) —
/// الشاشة الأولى تمرّر `_grandTotal` إلى الثانية. فدوال هذا الملف تحمل النموذج
/// في اسمها كي لا يُخطئ قارئٌ ولا تُخلط الحالتان.
///
/// **لا تقرّب هذه الدوال.** مواضع الاستخدام تختلف في التقريب: بعضها يقرّب إلى
/// منزلتين (`roundToDouble`) وبعضها خام. فالتقريب يبقى عند الاستخدام كما كان،
/// وهذه الدوال تُعيد القيمة الخام حرفياً كما كانت الصيغة المكتوبة يدوياً.
///
/// يحرسه `test/vat_test.dart` بفحص خاصيّة: تطابق كل دالة هنا مع الصيغة الحرفية
/// القديمة على عشرين ألف قيمة، لا على أمثلة مختارة.
library;

/// نسبة الضريبة (١٥٪). المصدر الوحيد — لا تُكتب `0.15` في مكان آخر.
const double kVatRate = 0.15;

/// معامل الإجمالي الشامل (١.١٥).
///
/// `1 + 0.15` يساوي `1.15` **بتةً ببتة** في IEEE754 (كلاهما
/// `1.1499999999999999112`)، فاستبدال الحرفيّ بهذا الثابت لا يغيّر رقماً واحداً.
/// تحقّقتُ من ذلك في Dart وNode على عشرين ألف قيمة قبل الاستبدال.
const double kVatMultiplier = 1 + kVatRate;

// ── النموذج أ: الضريبة تُضاف فوق الأساس ──────────────────────────────────

/// الضريبة المحسوبة **فوق** أساسٍ غير شامل.
double vatOnBase(double base) => base * kVatRate;

/// الإجمالي الشامل من أساسٍ غير شامل.
double grossFromBase(double base) => base * kVatMultiplier;

/// الإجمالي الشامل من أساس، مقرَّباً إلى منزلتين — صيغة ما يُشحن على العميل
/// ويُخزَّن في حقل `amount`، وهي ما يطابقه التسعير الخادمي.
double grossFromBaseRounded(double base) =>
    ((base * kVatMultiplier) * 100).roundToDouble() / 100;

// ── النموذج ب: الضريبة تُستخرج من إجمالٍ شامل ────────────────────────────

/// الصافي قبل الضريبة من إجمالٍ **شامل** لها.
double netFromGross(double gross) => gross / kVatMultiplier;

/// حصّة الضريبة داخل إجمالٍ **شامل** لها.
double vatInGross(double gross) => gross - gross / kVatMultiplier;
