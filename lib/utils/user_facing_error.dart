/// **سببٌ عربيٌّ يَكتبُه الخادمُ ثمّ يُطرَحُ قبلَ أن يَبلغَها (2026-10-07).**
///
/// `payWithWallet` يَرمي سبعةَ أسبابٍ عربيّةٍ مكتوبةٍ للعميلةِ بعينِها
/// («الرصيد غير كافٍ»، «المبلغ لا يطابق السعر المعتمد لمنطقتك»، «لا يمكن
/// الدفع لطلب مستخدم آخر»…)، و`payContractWithWallet` ستّةً،
/// و`redeemQatratPoints` ثلاثةً. وكان `GlobalErrorHandler.handleError` —
/// الذي تَصُبُّ فيه ثلاثُ شاشاتٍ عميليّةٍ ومنها شاشةُ الدفع —
/// **يُطابِقُ ثلاثَ كلماتٍ ويَطرحُ `message` كلَّه**، فيَقعُ على
/// «حدث خطأ غير متوقع. يُرجى المحاولة مرة أخرى.»
///
/// و«أعيدي المحاولة» على «الرصيد غير كافٍ» **نصيحةٌ خاطئةٌ لا ناقصة**:
/// إعادةُ المحاولةِ بالرصيدِ نفسِه تَفشلُ فشلاً مطابقاً، أبداً — فتُعيدُ
/// العميلةُ الكرَّةَ على زرِّ الدفعِ ولا تَعرفُ أنّ عليها أن تُعبّئَ
/// محفظتَها أو تَختارَ طريقةً أخرى.
///
/// **والقاعدةُ مقرَّرةٌ ومُنفَّذةٌ في سطحَين من خمسة** — وهو النمطُ المسجَّلُ
/// في هذا المشروعِ مرّاتٍ: `tamara_service` يَقولُها بأدقِّ صياغةٍ («يَصلُ
/// النصُّ كما هو، فإن غابَ… وقعنا على نصٍّ عربيٍّ عامّ بدل تسريبِ نصٍّ
/// لاتينيٍّ في واجهةٍ عربيّة»)، وفرعُ `FirebaseFunctionsException` في
/// استبدالِ القطراتِ يَقولُها ناقصةً (`e.message ??` بلا فحصِ عربيّةٍ، فرسالةُ
/// منصّةٍ إنجليزيّةٌ تُطبَعُ خامّةً في شريطٍ عربيّ). والثلاثةُ الباقيةُ
/// تَطرحُها: المُعالِجُ العامُّ، وفرعُ تمارا في شاشةِ دفعِ المتجر (يَطبعُ
/// الاحتياطيَّ العامَّ **أيّاً كان** ما قالَه الخادم)، وفرعُ تمارا في ملخّصِ
/// الدفعِ (عبرَ المُعالِجِ العامّ).
///
/// فتَسكنُ هنا مرّةً واحدةً، نقيّةً فتُختبَرُ بلا Firebase.
///
/// **وجملُها الثابتةُ بلا جنسٍ عمداً.** `GlobalErrorHandler` غيرُ مُقيَّدٍ بدورٍ
/// (قرارٌ مسجَّلٌ في `feminine_address_test`: «يَعرضُه كلُّ دور»)، فأيُّ جملةٍ
/// تَسكنُ هنا يَقرؤها السائقُ والمالكُ كما تَقرؤها هي — ولذلك «يُرجى» و«إعادة
/// المحاولة» لا «أعيدي». وقد عضَّ ذلك الحارسُ على أوّلِ صياغةٍ لهذا الملفِّ:
/// كانت «تحقّقي من الشبكة». وما يَخُصُّها وحدَها يُمرَّرُ من موضعِ النداءِ
/// في [fallback] (ومن هناك يُؤنَّث).
///
/// ─────────────────────────────────────────────────────────────────────────
/// **وما لا يَمُرُّ، ولمَ:** ليس كلُّ نصٍّ عربيٍّ في استثناءٍ جملةً لها.
/// `store_service` يَرمي «المنتج غير موجود في قاعدة البيانات: $productId» —
/// عربيٌّ، ويَحملُ معرّفَ مستندٍ واسمَ قاعدةِ بياناتٍ لا معنى لهما عندها.
/// فالقاعدةُ **بالحاملِ لا باللغة**: `HttpsError` من خادمِنا (كلُّ رسائلِه
/// مكتوبةٌ لها ومُخاطَبةٌ بالمؤنَّث)، أو حاملٌ يُعلِنُ ذلك عن نفسِه
/// (`UserFacingFailure`). وما عدا ذلك يُشخَّصُ من الشكلِ ولا يُسرَّب.
/// ─────────────────────────────────────────────────────────────────────────
library;

import 'dart:async';

import 'package:cloud_functions/cloud_functions.dart';
import 'package:firebase_core/firebase_core.dart';

/// استثناءٌ يُعلِنُ أنّ [message] فيه **جملةٌ عربيّةٌ كُتبت للعميلة**،
/// فتُعرَضُ كما هي.
///
/// التصريحُ هو العقدُ: صنفٌ يُنفّذُه يُقِرُّ أنّ رسالتَه مُراجَعةٌ للعرضِ لا
/// تشخيصٌ — ولذلك يُفرَّقُ عن `Exception(نصٍّ عربيّ)` العامّ (انظر أعلاه).
/// وما يَلزمُ للسجلِّ يُحمَلُ في حقلٍ آخرَ (`detail` في `MoyasarPayFailure`).
abstract interface class UserFacingFailure implements Exception {
  String get message;
}

/// الجملةُ الأخيرةُ حين لا نَعرفُ شيئاً — ولا تَنسبُ السببَ إلى أحد.
const String kGenericErrorMessage = 'حدث خطأ غير متوقع. يُرجى المحاولة مرة أخرى.';

/// انقطاعُ الشبكةِ — جملةٌ واحدةٌ لفرعَي المهلةِ والمقبس.
const String kNetworkErrorMessage =
    'لا يوجد اتصال بالإنترنت. يُرجى التحقق من الشبكة وإعادة المحاولة.';

final RegExp _arabic = RegExp(r'[ء-ي]');

/// هل يَحملُ النصُّ حرفاً عربيّاً — أي هل كُتبَ لها أصلاً؟
bool _isArabic(String s) => _arabic.hasMatch(s);

/// ماذا نَعرضُ لها عن هذا الخطأ؟
///
/// الأولويّةُ مقصودة:
///
///  1. **سببُ الخادمِ** إن كان عربيّاً — فهو وحدَه يَعرفُ *لماذا*، ويَسبقُ
///     التصنيفَ بالرمزِ لأنّ «لا يمكن الدفع لطلب مستخدم آخر» أنفعُ من «ليس
///     لديك الصلاحية». وشرطُ العربيّةِ ليس تزيّداً: رسائلُ المنصّةِ نفسِها
///     (`internal`، `deadline-exceeded`) إنجليزيّةٌ، وتسريبُها يُنتجُ
///     «[firebase_functions/internal] internal» في شريطٍ عربيّ — وهو عطلٌ
///     مسجَّلٌ في هذا المشروعِ وله حارسُه.
///  2. **حاملٌ يُعلِنُ جملتَه** (`UserFacingFailure`).
///  3. **تصنيفٌ بالشكل** حين لا رسالةَ لها: انقطاعُ شبكةٍ، أو مهلةٌ، أو
///     صلاحيّة.
///  4. وإلّا [fallback] إن أعطاه المُنادي، وإلّا [kGenericErrorMessage].
///
/// و[fallback] يُبدِلُ **الجملةَ العامّةَ وحدَها** لا الفروعَ المُصنَّفةَ: سطرُ
/// البوّابةِ («تعذّر بدء الدفع بالتقسيط — … أو اختاري طريقةً أخرى») أنفعُ من
/// «حدث خطأ غير متوقع»، وأقلُّ صدقاً من «تعذّر الاتصال بالإنترنت» حين يَكونُ
/// ذاك هو السبب.
String userFacingError(Object? error, {String? fallback}) {
  if (error is FirebaseFunctionsException) {
    final String m = (error.message ?? '').trim();
    if (_isArabic(m)) return m;
  }
  if (error is UserFacingFailure) {
    final String m = error.message.trim();
    if (m.isNotEmpty) return m;
  }

  // **المهلةُ فرعٌ لازمٌ لا تحسيناً.** `kNetCallTimeout` و`kAuthTimeout`
  // و`firstEventTimeout` حوّلت التعليقَ الأبديَّ إلى `TimeoutException` —
  // ونصُّها «TimeoutException after 0:00:20.000000: Future not completed»
  // لا يَحملُ «network» ولا «unavailable»، فكانت تَقعُ على «حدث خطأ غير
  // متوقع» بينما السببُ انقطاعُ شبكةٍ تَعرفُ العميلةُ كيف تُعالِجُه.
  // وكذلك `SocketException`: «Failed host lookup» لا تَحملُ أيَّ منهما.
  if (error is TimeoutException) return kNetworkErrorMessage;

  final String s = error?.toString() ?? '';
  if (s.contains('network') ||
      s.contains('offline') ||
      s.contains('Failed host lookup') ||
      s.contains('SocketException')) {
    return kNetworkErrorMessage;
  }
  if (s.contains('unavailable')) {
    return 'تعذّر الاتصال بالخادم. يرجى المحاولة مرة أخرى.';
  }
  if (error is FirebaseException && error.code == 'permission-denied' ||
      s.contains('permission-denied')) {
    return 'ليس لديك الصلاحية لإتمام هذه العملية.';
  }
  return fallback ?? kGenericErrorMessage;
}
