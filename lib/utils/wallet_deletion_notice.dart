/// «هل نُحذّرُها من رصيدٍ سيُحجَزُ إلى الأبد؟» — وجوابُه **ثلاثةُ** حالاتٍ لا
/// حالتان.
///
/// حذفُ الحسابِ لا رجعةَ فيه: المعرّفُ لا يَعودُ قابلاً لتسجيلِ الدخول، فرصيدُ
/// المحفظةِ يُحجَزُ بلا سبيلٍ إليه. وشرطُ التحذيرِ كان
/// `!_walletError && _walletBalance > 0` — فالتحذيرُ يَغيبُ في **حالتَين**
/// يَجبُ أن يَظهرَ فيهما:
///
///   * **المحفظةُ لم تُحمَّل بعد** (`_walletLoaded == false`): الرصيدُ `0.0`
///     ابتداءً، فالشرطُ كاذب. عميلةٌ تَفتحُ حوارَ الحذفِ قبلَ أن تَكتملَ
///     القراءةُ **لا تُخبَرُ بمالِها** وتَحذفُ حسابَها.
///   * **فشلت القراءة** (`_walletError`): الشرطُ يَكتمُ التحذيرَ صراحةً.
///     والتعليقُ فوقَه يَقولُ «القرارُ قرارُها» — ولا تَقدرُ أن تُقرّرَ ما لا
///     تُخبَرُ به.
///
/// والشكلُ الصحيحُ كان في الملفِّ نفسِه: كلُّ مواضعِ العرضِ الأخرى
/// (`$_walletBalance`، شريحةُ الاستبدال) تَفحصُ `_walletLoaded` **و**
/// `_walletError`. هذا الموضعُ وحدَه — وهو الأخطرُ — يَفحصُ الثانيَ فقط،
/// وهي الغلطةُ نفسُها التي صُحّحت في شريحةِ قطراتٍ في هذه الشاشةِ من قبل.
///
/// القاعدةُ: **عندَ الجهلِ نُحذّر**، لا نَسكت.
library;

/// ما يُعرَضُ في حوارِ تأكيدِ الحذف.
enum WalletDeletionNotice {
  /// الرصيدُ معروفٌ وصفرٌ — لا شيءَ يُقال.
  none,

  /// رصيدٌ قائمٌ معروفُ المقدار — يُذكَرُ بالرقم.
  balance,

  /// تعذّر معرفةُ الرصيدِ (جارٍ التحميلُ أو فشلَ) — يُحذَّرُ بلا رقم.
  unknown,
}

/// القرارُ نقيٌّ كي يُختبَرَ بلا Firebase.
WalletDeletionNotice walletDeletionNotice({
  required bool loaded,
  required bool error,
  required double balance,
}) {
  if (error || !loaded) return WalletDeletionNotice.unknown;
  // سالبٌ لا يُحجَزُ (دَينٌ لا رصيد) فلا يُحذَّرُ منه، والصفرُ لا شيء.
  return balance > 0 ? WalletDeletionNotice.balance : WalletDeletionNotice.none;
}
