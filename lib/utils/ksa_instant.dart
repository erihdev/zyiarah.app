/// **لحظةُ الموعدِ من ساعةِ حائطٍ سعوديّةٍ — لا من منطقةِ الجهاز.**
///
/// الموعدُ يُخزَّنُ **مرّتَين** على مستندِ الطلب، وهذا مقصود: حقلا الحجزِ
/// (`booking_date` و`booking_time_slot`) **ساعةُ حائطٍ** يَقرؤها
/// `functions/capacity.js` وبطاقةُ السائقِ والفاتورةُ والتذكير، و`service_date`
/// **لحظةٌ مطلقةٌ** تَقرؤها نوافذُ الخادمِ (فحصُ تعارضِ المُسنِد، ومكنسةُ
/// الطلبِ المدفوعِ بلا سائق، والتذكيرُ قبلَ أربعٍ وعشرين ساعة).
///
/// **والأُولى كانت مستقلّةً عن منطقةِ الجهازِ والثانيةُ لا.** حقلا الحجزِ
/// يُشتَقّانِ من **مكوّناتِ** ما اختارَه الإنسانُ (`lib/utils/booking_fields.dart`
/// يَقولُه نصّاً: «ولا يَتأثّرُ بمنطقةِ جهازِه»)، أمّا اللحظةُ فكانت
/// `Timestamp.fromDate(<ساعةُ حائطٍ محلّيّة>)` — و`DateTime(y, m, d, h)` في
/// دارت **محلّيّةٌ**، فـ`Timestamp.fromDate` تَأخذُ اللحظةَ التي تَقعُ فيها تلك
/// الساعةُ **في منطقةِ الجهاز**. فجهازٌ على UTC يُخزّنُ «14:00» لحظةً هي
/// 17:00 بالرياض، ومستندُ الطلبِ يَحملُ تمثيلَين للموعدِ الواحدِ **لا
/// يَتّفقان**.
///
/// **والقرارُ مُسجَّلٌ ومُنفَّذٌ سلفاً في المسارِ الخادميّ**، وهو ما يَجعلُ
/// هذا توحيداً لا اختراعاً: العميلُ يُرسِلُ الموعدَ نفسَه في بيانات الدفعِ
/// نصّاً **ساذجاً** (`toIso8601String()` بلا لاحقةِ منطقة)، و`parseKsaIso`
/// تَقرأُ الساذجَ **بتوقيتِ الرياضِ** بتعليقٍ صريح: «قصدُ المرسِلِ توقيتُ
/// الرياض». فمسارُ Apple Pay — حيث يَبني الخادمُ المستندَ من بيانات الدفعِ —
/// يُخزّنُ اللحظةَ الصحيحةَ، والمسارُ المباشرُ يُخزّنُ لحظةَ الجهاز: **نفسُ
/// العميلةِ ونفسُ الحجزِ بلحظتَين مختلفتَين بحسبِ وسيلةِ الدفع**.
///
/// وكذلك في سطحَي الإدارة: فرعُ النداءِ الخادميِّ يُمرّرُ `scheduledIso`
/// ساذجاً (صحيح)، والفرعُ المباشرُ في الشاشةِ نفسِها يَكتبُ
/// `Timestamp.fromDate(<محلّيّة>)` — وتعليقُ لوحةِ الويبِ يَشرحُ العطلَ
/// بنصِّه على بُعدِ أربعةِ أسطرٍ من الفرعِ الذي يَحملُه: «متصفحٌ خارج
/// السعودية يخزّن لحظةً مختلفة عن تطبيق الأدمن لنفس «14:00»».
///
/// **وما يَنكسِرُ باللحظةِ المُزاحة:** `capacity.js` يَعُدُّ السائقَ مشغولاً
/// من حقلَي الحجزِ (الصحيحَين) بينما `_findFreeDriverForSlot` يَفحصُ التعارضَ
/// من `service_date` (المُزاحة) — فالعرضُ والمُسنِدُ يَفترقان، وهي الحادثةُ
/// المسجَّلةُ بنصِّها: «يومٌ ظهرَ متاحاً، دُفِع، فلم يُوجَد سائقٌ مؤهَّل،
/// فعلِقَ الطلبُ حتى الاسترداد الآلي».
///
/// **كامنٌ لا حيٌّ، ويُقالُ بحدِّه:** يَلزمُه جهازٌ أو متصفّحٌ خارجَ
/// توقيتِ الرياض — عميلةٌ مسافرةٌ تَحجزُ لبيتها، أو جهازٌ بمنطقةٍ مضبوطةٍ
/// بيدٍ خطأً، أو أدمنٌ يَفتحُ اللوحةَ من الخارج. ولا توقيتَ صيفيَّ في
/// السعوديّة، فداخلَها لا يَقعُ أبداً. والإصلاحُ **حافظُ السلوكِ على +03**:
/// الصيغتانِ تُعطيانِ اللحظةَ نفسَها بالضبطِ هناك.
library;

/// إزاحةُ السعوديّةِ عن UTC — ثابتةٌ على مدارِ السنةِ (لا توقيتَ صيفيّاً).
/// نظيرةُ `KSA_OFFSET_MS` في `functions/ksa_time.js`، ومشدودةٌ بها.
const Duration kKsaUtcOffset = Duration(hours: 3);

/// اللحظةُ التي تَقعُ فيها ساعةُ الحائطِ [wall] **بتوقيتِ الرياض**.
///
/// تُقرأُ **مكوّناتُ** [wall] لا لحظتُها، فمنطقةُ الجهازِ لا تَدخلُ الحساب —
/// وهو عينُ ما تَفعلُه `bookingDateOf`/`bookingTimeSlotOf`، فيَتّفقُ
/// التمثيلانِ على مستندِ الطلبِ بالبناء.
DateTime ksaInstantOf(DateTime wall) => DateTime.utc(
      wall.year,
      wall.month,
      wall.day,
      wall.hour,
      wall.minute,
      wall.second,
      wall.millisecond,
      wall.microsecond,
    ).subtract(kKsaUtcOffset);

/// **ساعةُ الحائطِ السعوديّةُ للحظةٍ مطلقة — عكسُ [ksaInstantOf] بالضبط.**
///
/// الاتّجاهُ الذي كان ناقصاً: الوحدةُ تَحملُ «ساعةُ حائطٍ ← لحظة» وحدَه،
/// فكلُّ مَن أرادَ **طبعَ** لحظةٍ مخزَّنةٍ قرأَ مكوّناتَها محلّيّاً — أي
/// بمنطقةِ جهازِ القارئ. تُقرأُ هنا من `toUtc()` ثمّ تُزاح، فالمنطقةُ لا
/// تَدخلُ الحساب؛ والناتجُ `DateTime` **محلّيُّ النكهةِ بقصد** كـ
/// [ksaTodayWall]: مكوّناتُه هي ما يُطبَع، ولحظتُه لا تُستعمَل.
DateTime ksaWallOf(DateTime instant) {
  final r = instant.toUtc().add(kKsaUtcOffset);
  return DateTime(r.year, r.month, r.day, r.hour, r.minute, r.second,
      r.millisecond, r.microsecond);
}

/// **تاريخُ الرياضِ للحظةٍ مخزَّنةٍ، يوماً بلا ساعة** — لوثيقةِ العقد.
///
/// «تاريخ الإصدار / Issue Date» في ملفِّ العقدِ، وتاريخُه في بطاقةِ «عقودي»،
/// كلاهما `intl.DateFormat(…).format(createdAt)` و`createdAt` لحظةٌ مطلقةٌ من
/// `Timestamp.toDate()` — فالمطبوعُ تاريخُ **جهازِ القارئ**. ودقّةُ اليومِ
/// تَعني أنّ العطلَ يَقعُ عند حدِّ اليومِ وحدَه: عقدٌ أُنشئ الواحدةَ صباحاً
/// بالرياضِ يُطبَعُ بتاريخِ **أمس** على جهازٍ غربيَّ الإزاحة.
String ksaDateText(DateTime instant) {
  final DateTime w = ksaWallOf(instant);
  String two(int n) => n.toString().padLeft(2, '0');
  return '${w.year}-${two(w.month)}-${two(w.day)}';
}

/// **تاريخُ الرياضِ الحاليُّ ساعةَ حائطٍ** — `DateTime` مكوّناتُه Y/M/D
/// بتوقيتِ الرياضِ عند منتصفِ الليل، **محلّيُّ النكهةِ بقصد**: يُقارَنُ بما
/// تُعيدُه مُنتقياتُ التاريخِ وبما تَحملُه حقولُ الموعدِ في الشاشات، وتلك
/// كلُّها ساعةُ حائطٍ لا لحظةٌ مطلقة — والخادمُ يَقرأُ النصَّ الساذجَ
/// بتوقيتِ الرياضِ (`parseKsaIso`)، فالمقارنةُ بالمكوّناتِ هي عينُ ما يَفعلُه.
///
/// فجهازٌ على UTC عند الواحدةِ صباحاً يُعطي تاريخَ الرياضِ (الرابعةَ صباحاً،
/// اليومُ نفسُه)، وجهازٌ غربيَّ الإزاحةِ لا يُعطي «أمس».
///
/// [nowUtc] للفحصِ وحدَه؛ المواضعُ الحقيقيّةُ تَترُكُه فارغاً.
DateTime ksaTodayWall([DateTime? nowUtc]) {
  final r = (nowUtc ?? DateTime.now()).toUtc().add(kKsaUtcOffset);
  return DateTime(r.year, r.month, r.day);
}
