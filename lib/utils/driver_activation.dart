/// **تعطيلُ سائقٍ وتفعيلُه: ثلاثةُ حقولٍ تُكتَبُ معاً، في موضعٍ واحد.**
///
/// الخادمُ يَقرأُ `is_active` وحدَه لأهليّةِ الإسناد (`isAssignableDriver` في
/// `functions/drivers.js`)، ولوحةُ الويبِ تَبني **شارةَ الحالةِ ومفتاحَ
/// الإيقافِ** على `is_suspended`، و`is_available` حالةُ اتّصالِ السائقِ نفسِه
/// (يَضبطُها تطبيقُه عند الفتح، ويَضبطُها الخادمُ عند إكمالِ مهمّة).
///
/// **وقد وُجد هذا الخللُ وأُصلح مرّةً في موضعٍ واحدٍ من ثلاثة.** تعليقُ
/// `admin_compliance_screen` يَقولُه بنفسِه: «لوحةُ الويبِ تَبني شارةَ الحالةِ
/// ومفتاحَ الإيقافِ على `is_suspended`، فحظرٌ يَكتبُ `is_active` فقط كان
/// يُظهرُ السائقَ «نشطاً» في الويبِ رغمَ تعطيلِه هنا». وبَقي **مفتاحُ شاشةِ
/// السائقين نفسِها** — وهو المفتاحُ الرئيسيُّ — يَكتبُ `is_active` وحدَه.
///
/// فما يَراه الأدمنُ بعدَ تعطيلٍ من تطبيقِ الإدارة: في اللوحةِ شارةٌ خضراءُ
/// نابضةٌ «متاح»، وزرٌّ يَعرضُ «إيقاف» (لأنّ `is_suspended` ما زال `false`)
/// فيَبدو أنّه لم يُعطَّل، وعدّادُ «السائقون المتاحون» في الرئيسيّةِ يَعدُّه.
/// والإسنادُ نفسُه مرفوضٌ خادميّاً («السائق غير نشط») — فالعطلُ في الصورةِ
/// والعدد، لا في المال: الأدمنُ يُخطّطُ على سعةٍ لا وجودَ لها.
///
/// **والتفعيلُ لا يَكتبُ `is_available`** بقصد: الاتّصالُ قرارُ السائقِ لا
/// قرارُ الأدمن، وزعمُ أنّه متّصلٌ لأنّنا أعدنا تفعيلَه كذبٌ على اللوحة.
library;

/// الحقولُ التي تُكتَبُ على `drivers/{id}` عند تعطيلِه أو تفعيلِه.
Map<String, Object?> driverActivationFields({required bool active}) => active
    ? const {'is_active': true, 'is_suspended': false}
    : const {'is_active': false, 'is_suspended': true, 'is_available': false};

/// هل يُعَدُّ هذا المستندُ معطَّلاً؟ أيُّ الحقلَين يَكفي — نفسُ قراءةِ
/// `unassignJobsOnDriverDisable` خادميّاً (`is_active === false ||
/// is_suspended === true`).
bool driverIsDisabled(Map<String, Object?> d) =>
    d['is_active'] == false || d['is_suspended'] == true;
