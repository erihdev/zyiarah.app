/// عرض الوقت والتاريخ بالعربيّة — **عرضاً فقط، لا تخزيناً.**
///
/// **قاعدة صارمة:** `booking_time_slot` يبقى مخزَّناً بصيغة 24 ساعة (`"HH:00"`).
/// الدالة الخادمية تحلّله بـ `parseInt(slot.split(":")[0])` لتعدّ السعة وتكشف
/// التداخل الزمني — فلو خُزِّن `"3:00 م"` لقرأته **3 صباحاً**، وانهار حساب السعة
/// بصمت: سلوت المساء يُحسب على الفجر، فتُقبل حجوزات لا سائق لها.
///
/// لذلك: التخزين 24، والعرض عبر هذه الدوال وحدها.
///
/// **ولمَ صارَ الملفُّ يَحملُ أسماءَ الأيّامِ والشهورِ أيضاً (2026-10-05):**
/// العميلةُ كانت تَرى وقتَها بثلاثِ صِيَغٍ في مسارِها الواحد — «3:00 م» في
/// مُنتقي الساعة، و«3:00 مساءً» في شريطِ الموعد (تحويلٌ مكتوبٌ بيدٍ سادساً
/// في `orders_list_screen`)، و«15:30» على بطاقةِ الطلب — وتاريخَها بصيغتَين:
/// «الأحد 12/10» في شريطِ الأيّام ثم «2026-10-12» في رقاقةِ الزيارةِ
/// المضافةِ تحتَه مباشرةً. فالتحويلُ هنا مرّةً واحدةً (`_hour12`/`_period`)
/// بثلاثِ صِياغاتٍ تَستعملُه، وأسماءُ الأيّامِ مرّةً واحدةً كانت مكتوبةً
/// بيدٍ في أربعةِ ملفّاتٍ عميليّة.
library;

// ── الأساس: قاعدةُ التحويلِ مرّةً واحدةً ───────────────────────────────────
// 0 و12 يُعرضان 12 لا 0: منتصف الليل «12:00 ص» والظهر «12:00 م».
int _hour12(int h24) => h24 % 12 == 0 ? 12 : h24 % 12;

/// لاحقةُ الفترة. الطويلةُ («صباحاً»/«مساءً») لجملةٍ مقروءةٍ كشريطِ الموعد،
/// والقصيرةُ («ص»/«م») لرقاقةٍ أو خانةٍ ضيّقة — والفرقُ قرارُ صياغةٍ لكلِّ
/// موضع، لا نسختانِ من القاعدة.
String _period(int h24, bool long) =>
    h24 < 12 ? (long ? 'صباحاً' : 'ص') : (long ? 'مساءً' : 'م');

/// **النواةُ: ساعةٌ ودقيقةٌ إلى نصِّ 12 ساعة.** كلُّ ما تَحتَها يَمرُّ بها،
/// فلا تَتكرّرُ قاعدةُ التحويلِ مرّةً أخرى.
///
/// [padHour] يُبطِّنُ الساعةَ بصفرٍ («02:15 م» بدل «2:15 م») — وهو صياغةُ
/// موضعَين قائمَين (بطاقةُ مهمّةِ السائق، وخطُّ زمنِ التتبّع)، أُبقيَ كما هو
/// لأنّ هذه الوحدةَ **حافظةٌ للسلوك**: جمعُ ثماني نسخٍ في قاعدةٍ واحدةٍ لا
/// يُعادُ به تنسيقُ ما كان صحيحاً. وتوحيدُ التبطينِ قرارُ صياغةٍ لا إصلاحٌ.
String formatClock12(int hour24, int minute,
    {bool longPeriod = false, bool padHour = false}) {
  final h = hour24 % 24;
  final hs = padHour
      ? _hour12(h).toString().padLeft(2, '0')
      : _hour12(h).toString();
  return '$hs:${minute.toString().padLeft(2, '0')} ${_period(h, longPeriod)}';
}

/// يحوّل ساعة (0–23) إلى نص عربي بنظام 12 ساعة: `8` → «8:00 ص»، `15` → «3:00 م».
String formatHour12(int hour24) => formatClock12(hour24, 0);

/// يحوّل خانة مخزَّنة (`"HH:00"` أو `"HH:mm"`) إلى نص 12 ساعة.
/// يُعيد النصّ كما هو إن تعذّر التحليل — لا يُخفي بياناً لا يفهمه.
String formatSlot12(String? slot) {
  if (slot == null || slot.isEmpty) return '';
  final parts = slot.split(':');
  final h = int.tryParse(parts.first);
  if (h == null || h < 0 || h > 23) return slot;
  final minutes = parts.length > 1 ? (int.tryParse(parts[1]) ?? 0) : 0;
  return formatClock12(h, minutes);
}

/// مدى زمني: «8:00 ص – 12:00 م».
String formatRange12(int startHour, int endHour) =>
    '${formatHour12(startHour)} – ${formatHour12(endHour)}';

/// وقتُ لحظةٍ بنظام 12 ساعة: «3:30 م»، أو «3:30 مساءً» بـ[longPeriod].
///
/// هذه هي الوجهةُ الوحيدةُ لعرضِ وقتِ `DateTime` للعميلة — `DateFormat('HH:mm')`
/// كان يَعرضُ لها 24 ساعةً على بطاقةِ الطلبِ وفي الدعمِ بينما سائرُ الواجهةِ
/// 12، وتحويلٌ مكتوبٌ بيدٍ في شريطِ الموعدِ اختلفَ في كلمةِ الفترة.
String formatTime12(DateTime t, {bool longPeriod = false, bool padHour = false}) =>
    formatClock12(t.hour, t.minute, longPeriod: longPeriod, padHour: padHour);

// ── أسماءُ الأيّامِ والشهور ────────────────────────────────────────────────

/// الأحدُ أوّلاً — ترتيبُ `DateTime.weekday % 7` بعينِه.
///
/// **ملاحظة:** `DriverSchedule.dayNames` تَبدأُ بالسبتِ عمداً ولا تُستبدَلُ
/// بهذه: شبكتُه الأسبوعيّةُ مُرتكِزةٌ على السبتِ (`daysSinceSaturday`)، فهي
/// تسميةُ شبكةٍ لا تسميةُ يومٍ مفرد.
const List<String> arabicWeekdayNames = [
  'الأحد',
  'الاثنين',
  'الثلاثاء',
  'الأربعاء',
  'الخميس',
  'الجمعة',
  'السبت',
];

const List<String> arabicMonthNames = [
  'يناير',
  'فبراير',
  'مارس',
  'أبريل',
  'مايو',
  'يونيو',
  'يوليو',
  'أغسطس',
  'سبتمبر',
  'أكتوبر',
  'نوفمبر',
  'ديسمبر',
];

/// اسمُ يومِ [d] بالعربيّة. كان مكتوباً بيدٍ في أربعةِ ملفّاتٍ عميليّة
/// بترتيبَين مختلفَين وتهجئتَين لـ«الاثنين» — فالعميلةُ تَحجزُ يومَ «الاثنين»
/// ويَقولُ شريطُ موعدِها «الإثنين».
String arabicWeekday(DateTime d) => arabicWeekdayNames[d.weekday % 7];

/// اسمُ شهرِ [d] بالعربيّة.
String arabicMonth(DateTime d) => arabicMonthNames[d.month - 1];
