/// **الرقمُ المرجعيُّ للعقد — واحدٌ لكلِّ سطح.**
///
/// كان خمسةَ أشكالٍ لعقدٍ واحد، وأثرُها أنّ ما يُطبَعُ على الوثيقةِ الموقَّعةِ
/// لا يُوجَدُ في أيِّ قائمةٍ إداريّةٍ ولا يُطابِقُه أيُّ بحث:
///
///   • **ما يُطبَعُ على الـPDF** (وفي رمزِ QR منه وفي اسمِ الملفّ) هو الحقلُ
///     المخزَّنُ `contractId` الذي تَمنحُه شاشةُ التوثيقِ
///     (`CTR-` + سبعةُ أرقامٍ من الطابعِ الزمنيّ) — وهذا هو الرقمُ الذي
///     تَقرؤه العميلةُ وتَقولُه للدعم.
///   • **وصفُّ القائمةِ عند الأدمن** (التطبيقُ واللوحةُ معاً) كان
///     `doc.id.substring(0, 8)` — معرّفُ المستندِ، قيمةٌ أخرى تماماً.
///   • **وبحثُ العقودِ في السطحَين** تلميحُه «ابحث … أو **رقم العقد**»
///     ويُرشِّحُ معرّفَ المستندِ وحدَه — فالرقمُ المطبوعُ على العقدِ
///     **غيرُ قابلٍ للعثور** بالبناءِ: ليس في المعرّف، والحقلُ المخزَّنُ ليس
///     في المُرشِّحِ أصلاً (ولوحةُ الويبِ لم تَكن تَقرأُ الحقلَ إطلاقاً).
///   • **وصفُّ العميلةِ** كان يَقطعُ المخزَّنَ إلى ثمانيةِ محارف
///     (`CTR-1234`) — فتَقتبسُ ثمانيةً من أحدَ عشَرَ.
///   • **واحتياطُ الـPDF الإداريِّ** كان النصَّ الحرفيَّ `'XXXX'`، وشاشةُ
///     التوثيقِ تَعرضُ `CTR-XXXX` نائبةً قبلَ أن يُمنَحَ الرقمُ أصلاً.
///
/// والقاعدةُ: **المخزَّنُ إن وُجد، وإلّا معرّفُ المستند** — مقطوعاً عند ثمانيةٍ
/// **وهو احتياطُ هُويّةٍ لا رقمٌ مرجعيّ**، فقطعُه لا يُفسِدُ شيئاً، بخلافِ
/// قطعِ `CTR-…` الذي يُنتجُ رقماً آخر. ولا قطعَ أعمى: `substring(0, 8)` على
/// معرّفٍ أقصرَ يَرمي `RangeError` — وهو ما كان مَحروساً في شاشةِ العميلةِ
/// (`_shortRef`) ومكشوفاً في موضعَي الإدارة.
library;

/// الرقمُ المعروضُ: المخزَّنُ المُهذَّبُ إن كان نصّاً غيرَ فارغ، وإلّا
/// ثمانيةُ محارفَ من معرّفِ المستندِ بحروفٍ كبيرة.
String contractRef(Object? stored, String docId) {
  if (stored is String && stored.trim().isNotEmpty) return stored.trim();
  final s = docId.toUpperCase();
  return s.length >= 8 ? s.substring(0, 8) : s;
}

/// أيُطابِقُ [query] هذا العقد؟ — الرقمُ المعروضُ **أو** معرّفُ المستندِ
/// كاملاً: فالمعرّفُ هو ما تَحملُه الروابطُ والسجلّاتُ القديمةُ، وإسقاطُه
/// يُفقِدُ الأدمنَ ما كان يَبحثُ به قبلَ هذا التوحيد.
bool contractRefMatches(Object? stored, String docId, String query) {
  final q = query.trim().toLowerCase();
  if (q.isEmpty) return true;
  return contractRef(stored, docId).toLowerCase().contains(q) ||
      docId.toLowerCase().contains(q);
}
