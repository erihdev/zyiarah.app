/// نطاق ساعات عملٍ يقبله الخادم — **`end > start` دائماً**.
///
/// `zoneDayScheduleForDate` في `functions/index.js` يشترط حرفيّاً
/// `Number.isInteger(s) && Number.isInteger(e) && e > s`، وإن لم يتحقّق أعاد
/// `null` — أي **مغلق كلّ اليوم**. فنطاقٌ طرفاه متساويان لا يُرفَض برسالة، بل
/// يُقرأ إغلاقاً: لا إتاحة، ولا حجز، ولا خطأ في أي مكان يُنبّه أحداً.
///
/// وقائمتا الساعات في محرّري الجدول (التطبيق والويب) مستقلّتان على 0..23، فكان
/// المحرّران يسمحان بذلك. ومحرّر التطبيق يُقيّده منذ البداية — تحريك البداية
/// يدفع النهاية والعكس — إلّا في **طرف المدى**: بداية 23 تدفع النهاية إلى
/// `(24).clamp(1, 23)` = 23، فيتساوى الطرفان ويعود العطل الذي جاء القيد يمنعه.
/// (وُجد بفحص مرآة الويب على كل أزواج الساعات، لا على أمثلة.)
///
/// فهنا القاعدة نقيّةً: البداية تُقَصّ عند 22 والنهاية عند 1، فلا يتساويان أبداً.
library;

/// البداية صارت [start]: تدفع النهاية إلى `start + 1` إن لزِم.
///
/// وتُقَصّ البداية عند 22 — لا بدايةَ في الساعة 23، فالنهاية لا تتجاوز 23 فلا
/// تبقى ساعةٌ واحدة.
({int start, int end}) hourRangeWithStart(int start, int end) {
  final s = start.clamp(0, 22);
  return end <= s ? (start: s, end: (s + 1).clamp(1, 23)) : (start: s, end: end);
}

/// النهاية صارت [end]: تسحب البداية إلى `end - 1` إن لزِم.
///
/// وتُقَصّ النهاية عند 1 — للسبب المقابل: نهايةٌ في 0 لا تدع ساعةً قبلها.
({int start, int end}) hourRangeWithEnd(int start, int end) {
  final e = end.clamp(1, 23);
  return start >= e ? (start: (e - 1).clamp(0, 22), end: e) : (start: start, end: e);
}
