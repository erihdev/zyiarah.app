"use strict";

// حلُّ منطقةِ الطلبِ و«هل هذا النوعُ قابلٌ للتحقّقِ من سعره؟» — سؤالان كانا
// مكتوبَين في مسارَي الدفعِ بشكلَين مختلفَين، فاختلفَ المسارانِ فعلاً.
//
// **لا يَلمسُ هذا الملفُّ `getFirestore()`**: يَستقبلُ `db` أوّلَ وسيط (قاعدةُ
// الوحداتِ هنا — `refund_engine.js` ونظراؤه)، فيُختبَرُ بـ`db` مُزيَّفٍ بلا
// مُحاكٍ ولا شبكة.
//
// **ما وُجد (2026-10-05):** مسارُ ميسر يَحلُّ المنطقةَ بـ`zone_id` ثمّ
// بالاسم، ويُسمُ الطلبَ `price_unverifiable` ويُنبّهُ الإدارةَ إن كان نوعُه
// قابلاً للتسعيرِ وتعذّر حسابُه — «يَسدّ ثغرةَ إسقاطِ `zone_name` للتهرّبِ من
// التحقّق» بنصِّ تعليقِه. ومسارُ المحفظةِ كان يَقرأ `zone_name` وحدَه، وإن
// غابَ **تخطّى التحقّقَ كلَّه بلا وسمٍ ولا تنبيه**: الثغرةُ نفسُها مفتوحةً في
// المسارِ الآخر. ثلاثةُ فروقٍ بالضبط، اثنان منها حيّان:
//
//   1. `zone_id` لم يكن يُقرأ في مسارِ المحفظة — **كامن**: لا شيءَ في
//      المستودعِ يَكتبُ `zone_id` على طلبٍ (المفتاحُ يَظهرُ في تفاصيلِ
//      التدقيقِ وحدَها)، فالاسمُ هو ما يُحلُّ به اليومَ في المسارَين.
//   2. لا وسمَ `price_unverifiable` ولا تنبيهَ في مسارِ المحفظة — **حيّ**.
//   3. الخصمُ الموثوقُ لم يُطرَح في مسارِ المحفظة — **حيّ**، وأثرُه في
//      الاتجاهِ المُضرِّ بالعميلةِ: كوبونٌ نسبتُه أكثرُ من 50% يُنتجُ
//      `ratio < 0.5` فيُوسَمُ دفعٌ سليمٌ `price_mismatch`، وأكثرُ من 80%
//      يَهبطُ تحتَ عتبةِ الرفضِ فتُرفضُ دفعةٌ صحيحةٌ برسالةِ «المبلغ لا يطابق
//      السعر المعتمد لمنطقتك».
//
// و[isPriceableKind] كانت تُعدِّدُ أربعةَ أنواعٍ بيدها وتُغفلُ
// **`event_workers`** — وهو نوعٌ يُسعّرُه `pricing.js` فعلاً. فطلبُ عاملاتِ
// مناسباتٍ بلا `zone_name` كان يَتهرّبُ من التحقّقِ **بصمتٍ في المسارَين
// معاً**، وهو عينُ ما وُجد هذا الفحصُ ليَمنعَه. القائمةُ الآن من `pricing.js`
// نفسِها، و`price_verify.test.js` يُقارنُ كلَّ فرعِ `kind` فيها بالقائمةِ —
// فنوعٌ خامسٌ يُضافُ غداً يَفشلُ بدلَ أن يَتهرّب.

const {PRICEABLE_KINDS} = require("./pricing");

/**
 * مستندُ منطقةِ الطلبِ، أو `null` إن لم تُحَلّ. `zone_id` أوّلاً لأنّه ثابتٌ،
 * ثمّ الاسمُ (قابلٌ لإعادةِ التسمية).
 * @param {object} db مرجعُ Firestore (يُمرَّر، لا يُستدعى من هنا)
 * @param {object} od بياناتُ الطلب
 * @return {Promise<object|null>} بياناتُ المنطقة
 */
async function resolveZone(db, od) {
  if (!od) return null;
  if (od.zone_id) {
    const zd = await db.collection("service_zones").doc(String(od.zone_id)).get();
    if (zd.exists) return zd.data();
  }
  if (od.zone_name) {
    const zq = await db.collection("service_zones")
        .where("name", "==", od.zone_name).limit(1).get();
    if (!zq.empty) return zq.docs[0].data();
  }
  return null;
}

/**
 * نوعٌ يُعيدُ `pricing.js` حسابَ سعرِه — فتعذُّرُ حسابِه خللٌ يُنبَّهُ عليه،
 * لا صمت. طلبُ المتجرِ ليس منها (عناصرُه بلا معرّفِ منتجٍ في `service_meta`).
 * @param {object} od بياناتُ الطلب
 * @return {boolean} قابلٌ للتسعير
 */
function isPriceableKind(od) {
  if (!od) return false;
  const kind = od.service_meta && od.service_meta.kind;
  if (kind) return PRICEABLE_KINDS.includes(kind);
  // بلا `service_meta.kind` ⇒ **بالساعة**، وهو فرعُ `pricing.js` الجامع
  // (`prices[String(hours_contracted)] × worker_count`). وكان هذا السطرُ
  // `!!od.hours_contracted` — أي أنّ **صِدقَ الحقلِ الذي يكتبه العميلُ** هو
  // ما يُقرّرُ هل يَسري التحقّقُ أصلاً: `hours_contracted: 0` أو نصٌّ تالفٌ
  // أو إسقاطُ الحقلِ كلِّه يُحوّلُ «تعذّرَ التحقّقُ فننبّه» إلى «ليس من
  // نوعِنا فنصمت» — وهي ثغرةُ إسقاطِ `zone_name` بعينِها التي وُجد هذا
  // المُعيِّنُ لسدِّها، ونظيرُ إغفالِ `event_workers` عن `PRICEABLE_KINDS`.
  //
  // ولا إيجابيّةَ كاذبةً في المقابل: **كلُّ** مُنشئٍ لمستندِ `orders` في
  // المستودع يكتبُ `hours_contracted` (الشاشتان، ومسارا الدفعِ الأصليِّ
  // والتسوية، ومولِّدا زياراتِ العقد) — يَشُدُّه فحصٌ في
  // `price_verify.test.js` — فغيابُه لا يُنتجُه مسارٌ شريف. والفرعانِ
  // المُنادِيانِ يَسِمانِ ويُنبّهانِ ولا يَرفضانِ دفعاً، فالتوسيعُ لا يَصِلُ
  // جيبَ عميلة.
  return true;
}

module.exports = {resolveZone, isPriceableKind};
