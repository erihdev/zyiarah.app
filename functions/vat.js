"use strict";

// ضريبة القيمة المضافة — نظير `lib/utils/vat.dart` على الخادم.
//
// النسبة كانت مكتوبة يدوياً في index.js في أربعة مواضع، كلها على مسار التحقّق
// من المدفوعات: `Math.round(base * 1.15 * surge * 100) / 100`. وتغييرها حدث
// فعلاً في السعودية (٥٪ ← ١٥٪ في ٢٠٢٠)، وموضعٌ منسيّ على هذا المسار يعني
// مقارنةً خاطئة بين المدفوع والمتوقَّع — فإمّا قبولُ دفعٍ ناقص أو رفضُ دفعٍ سليم.
//
// `1 + 0.15` يساوي `1.15` بتةً ببتة في IEEE754، فالاستبدال لا يغيّر رقماً.
// يحرسه `functions/test/vat.test.js` بفحص خاصيّة على عشرين ألف قيمة.
//
// الاسم يحمل النموذج: الضريبة هنا **تُضاف فوق** الأساس (النموذج المعتمد
// خادمياً — `amount` المخزَّن = الأساس × ١.١٥)، لا تُستخرج من إجمالٍ شامل.

/** نسبة الضريبة (١٥٪) — المصدر الوحيد. */
const VAT_RATE = 0.15;

/** معامل الإجمالي الشامل (١.١٥). */
const VAT_MULTIPLIER = 1 + VAT_RATE;

/**
 * الإجمالي الشامل المتوقَّع من أساس، مقرَّباً إلى منزلتين — صيغة ما يُقارَن به
 * المدفوع. التقريب جزء من العقد مع العميل: الشاشة تعرض المقرَّب وتدفعه.
 * @param {number} base الأساس قبل الضريبة
 * @param {number} [surge=1] معامل الذروة (العقود الثابتة تمرّره 1 أو تتخطّاه)
 * @return {number} الإجمالي الشامل مقرَّباً إلى منزلتين
 */
function grossFromBaseRounded(base, surge = 1) {
  return Math.round(base * VAT_MULTIPLIER * surge * 100) / 100;
}

/**
 * الإجمالي الشامل الخام من أساس (بلا تقريب) — لحساباتٍ وسيطة تُقرَّب لاحقاً.
 * @param {number} base الأساس قبل الضريبة
 * @return {number} الإجمالي الشامل الخام
 */
function grossFromBase(base) {
  return base * VAT_MULTIPLIER;
}

module.exports = {
  VAT_RATE,
  VAT_MULTIPLIER,
  grossFromBaseRounded,
  grossFromBase,
};
