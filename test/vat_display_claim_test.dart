// حارس: **ما يُعرض للعميلة قبل الضريبة، فلا تُوصف بأنها شاملةٌ لها.**
//
// قرارُ المالك: كلُّ سعرٍ يراه العميلُ في شاشات الحجز **قبل** الضريبة، والـ15%
// تُضاف عند الدفع وتظهر في «تفاصيل الفاتورة» وحدها. الشاشاتُ تقول ذلك بثلاث
// جملٍ: «الإجمالي قبل الضريبة»، «تُضاف ضريبة القيمة المضافة 15% عند إتمام
// الطلب»، و«السعر قبل الضريبة ويشمل أدوات التنظيف الأساسية».
//
// ووُجد بتشغيل التطبيق (2026-10-04) أنّ `hourly_details_screen` كانت تقول فوق
// بطاقات الأسعار مباشرةً: «الأسعار **شاملة** الضريبة وتشمل كامل الكوادر
// المختارة» — والبطاقةُ تحتها تعرض `opt.basePrice`، أي الأساسَ قبل الضريبة
// (وتعليقُ الشيفرة فوقها يقول ذلك صراحةً). فالعميلةُ تقرأ أنّ 230 ر.س هي ما
// ستدفعه، ثم تُشحَن 264.50 في شاشة الدفع — وهي الجملةُ الأبرزُ موضعاً في
// الشاشة: مباشرةً تحت «اختر نوع سكنك:» وفوق الأرقام.
//
// والجملةُ نفسها كانت قد صُحِّحت مرّةً في **هذا الملفّ بعينه** (التعليق هناك
// يسجّل: «السعر صار يُعرض قبل الضريبة في كل الشاشات، فالنص القديم شامل
// الضريبة صار مناقضاً لما تراه») — وفُوِّت هذا الموضع. فالحارسُ يمنع الموضعَ
// الثالث لا الثاني.
//
// نطاقُ الحارس: شاشاتُ العميل والسائق (`lib/screens/**` خارج `admin/`). شاشاتُ
// الإدارة تقول «شامل الضريبة» بحقّ: المبالغُ المخزَّنة شاملةٌ للضريبة فعلاً،
// والتقاريرُ تعرض الإجمالي والصافي معاً.
import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

/// يحجب التعليقات دون إزاحةِ المواضع: أسطرُ التعليق الكاملة تُفرَّغ، والتعليقُ
/// الذيليّ `//` يُقطع — إلا ما سبقته نقطتان (`https://`). القاعدةُ نفسها
/// المستعملة في حارس تمارا وحارس نشر الدوالّ.
String _stripComments(String src) {
  final out = <String>[];
  for (final line in src.split('\n')) {
    final t = line.trimLeft();
    if (t.startsWith('//')) {
      out.add('');
      continue;
    }
    var cut = -1;
    for (var i = 0; i + 1 < line.length; i++) {
      if (line[i] == '/' && line[i + 1] == '/' && (i == 0 || line[i - 1] != ':')) {
        cut = i;
        break;
      }
    }
    out.add(cut < 0 ? line : line.substring(0, cut));
  }
  return out.join('\n');
}

const _claims = [
  'شامل الضريبة',
  'شاملة الضريبة',
  'شاملٌ الضريبة',
  'شاملاً الضريبة',
  'تشمل الضريبة',
  'يشمل الضريبة',
  'شاملة للضريبة',
  'شامل للضريبة',
];

void main() {
  group('لا دعوى «شامل الضريبة» في شاشةٍ تعرض ما قبلها', () {
    final files = Directory('lib/screens')
        .listSync(recursive: true)
        .whereType<File>()
        .where((f) => f.path.endsWith('.dart'))
        .where((f) => !f.path.contains('/admin/'))
        .toList()
      ..sort((a, b) => a.path.compareTo(b.path));

    test('الشاشات موجودة (حارسٌ لا يمسح شيئاً حارسٌ أجوف)', () {
      expect(files.length, greaterThan(20), reason: 'لم تُقرأ شاشاتُ العميل');
    });

    for (final f in files) {
      test('${f.path.split('/').last}: لا دعوى شمولٍ للضريبة', () {
        final code = _stripComments(f.readAsStringSync());
        for (final c in _claims) {
          expect(code.contains(c), isFalse,
              reason: '«$c» في ${f.path} — وأسعارُ شاشات الحجز تُعرض قبل '
                  'الضريبة. دعوى الشمول تجعل العميلةَ تُشحَن أكثر مما قرأت.');
        }
      });
    }
  });

  group('شاشةُ التنظيف المنزليّ: النصُّ يطابق الرقمَ تحته', () {
    final src = File('lib/screens/hourly_details_screen.dart').readAsStringSync();

    test('التسميةُ فوق البطاقات تقول «قبل الضريبة»', () {
      expect(src.contains('"الأسعار قبل الضريبة وتشمل كامل الكوادر المختارة"'),
          isTrue,
          reason: 'اختفت التسميةُ المُصحَّحة — إمّا عادت القديمة أو حُذِفت');
    });

    test('البطاقاتُ ما زالت تعرض الأساسَ لا الإجمالي', () {
      // لو صار المعروضُ `grossPrice` فالقاعدةُ تنقلب والنصُّ يلزم تغييرُه معها.
      expect(src.contains(r'Text("${formatSar(opt.basePrice)} ر.س"'), isTrue,
          reason: 'تغيّر المعروض — راجع نصَّ الضريبة فوقه قبل تعديل الحارس');
      expect(src.contains('opt.grossPrice'), isFalse);
    });

    test('الجملتان الأخريان حاضرتان (الشاشةُ متّسقة مع نفسها)', () {
      expect(src.contains('الإجمالي قبل الضريبة:'), isTrue);
      expect(src.contains('تُضاف ضريبة القيمة المضافة 15% عند إتمام الطلب'),
          isTrue);
    });

    test('حجبُ التعليقات لم يُفرِّغ الحارس', () {
      // الملفُّ يسجّل القرارَ بذكر العبارةِ القديمة في تعليقه. فلو كان الحجبُ
      // مُفرِطاً لما بقي شيءٌ يُفحَص — والعكسُ: لو لم يحجب لفشل على توثيقه.
      expect(src.contains('شاملة الضريبة'), isTrue,
          reason: 'العبارةُ القديمة تُذكر في التعليق الذي يشرح القرار');
      expect(_stripComments(src).contains('شاملة الضريبة'), isFalse,
          reason: 'الحجبُ لا يرى التعليق — سيفشل الحارسُ على توثيقه');
    });
  });
}
