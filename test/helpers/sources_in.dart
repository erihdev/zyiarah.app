import 'dart:io';

/// **كلُّ مسحٍ للملفّاتِ في الحُرّاسِ يَمُرُّ من هنا — بأرضيّةٍ مطلوبة.**
///
/// أربعةَ عشَرَ حارساً كان يَعُدُّ ملفّاتِه بـ`Directory(dir).listSync(...)`
/// **بلا أرضيّة**، فاختبارُ قضمٍ أفرغَ التعدادَ في كلٍّ منها أثبتَ أنّها
/// تَمُرُّ **خضراءَ** على مسحٍ لا يَرى شيئاً — ومنها حُرّاسُ قراراتِ الجذرِ
/// نفسِها (`no_cod`، `no_tabby`، `no_dead_code`، `no_dead_files`، VAT،
/// تحصينُ التخزين، بياناتُ البائعِ على الفاتورة).
///
/// وهذا ليس فرضيّاً: هذا المستودعُ شُحِنَ عليه مرّةً — أوّلُ صياغةٍ
/// لـ`google_fonts_pin_test` «عدَّت ثلاثةَ آباءٍ من `Platform.resolvedExecutable`
/// … فلم تَجِدْ شيئاً ورجعت مبكراً — **خضراءَ وجوفاء**». وطرائقُ الإفراغِ
/// عمليّةٌ كلُّها: نقلُ مجلّدٍ أو إعادةُ تسميتِه، أو مُرشِّحٌ يَضيق، أو
/// تشغيلٌ من جَذرٍ آخر.
///
/// فالأرضيّةُ **وسيطٌ مطلوبٌ** لا مُفترَض: قيمةٌ افتراضيّةٌ تُعيدُ العطلَ
/// نفسَه بصمتٍ عند موضعِ نداءٍ منسيّ — نفسُ قرارِ `passed` في قاعدةِ «تتبّع
/// السائق» و`audience` في بوّابةِ المنبثق.
///
/// ويُرمى `StateError` لا `expect`: هذه الدالّةُ تُنادى من نطاقِ `main`
/// أيضاً (بناءُ خرائطٍ قبلَ `test()`)، و`expect` هناك غيرُ مشروع
/// (`OutsideTestException`) — وهو فخٌّ سُجِّلَ في هذا المستودعِ مرّتَين.
List<File> sourcesIn(
  String dir, {
  required int atLeast,
  List<String> exts = const ['.dart'],
}) {
  final d = Directory(dir);
  if (!d.existsSync()) {
    throw StateError('مسحُ الحارس: المجلّدُ «$dir» غيرُ موجود — '
        'انتقلَ أو أُعيدت تسميتُه، والحارسُ كان سيَمُرُّ أخضرَ على لا شيء.');
  }
  final files = d
      .listSync(recursive: true)
      .whereType<File>()
      .where((f) => exts.any((x) => f.path.endsWith(x)))
      .toList();
  if (files.length < atLeast) {
    throw StateError('مسحُ الحارس: «$dir» أعطى ${files.length} ملفّاً '
        'والأرضيّةُ $atLeast — مسحٌ انحلَّ، والحارسُ بلا موضوع.');
  }
  return files;
}
