import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

import 'helpers/sources_in.dart';

/// **عشرونَ حارساً كانت تَمُرُّ خضراءَ على مسحٍ لا يَرى ملفّاً واحداً
/// (2026-10-08).**
///
/// أغلبُ حُرّاسِ هذا المستودعِ تَعُدُّ ملفّاتَها بنفسِها
/// (`Directory('lib').listSync(recursive: true)`) ثمّ تَمسحُ عن مصطلحٍ أو
/// تَجمعُ مجموعةً. و**المسحُ الذي يَنحلُّ إلى صفرٍ لا يَفشلُ: يَنجح** — فحصُ
/// «لا موضعَ يَحملُ كذا» على لا شيءٍ صحيحٌ منطقاً، فارغٌ أثراً.
///
/// وقد أُجريَ القياسُ لا الظنُّ: قُضِمَ تعدادُ **كلِّ** حارسٍ يَعُدُّ ملفّاتٍ
/// (٥٤ ملفّاً) واحداً واحداً — إفراغُ المُرشِّحِ وحدَه مع إبقاءِ ما بعدَه —
/// فمرَّ **عشرونَ** أخضرَ، ومنها حُرّاسُ قراراتِ الجذرِ نفسِها: لا دفعَ عند
/// الاستلام، ولا تابي، ولا شفرةَ ميّتةً، ولا ملفَّ بلا مستهلك، ونسبةُ
/// الضريبة، وتحصينُ التخزين، وبياناتُ البائعِ على الفاتورةِ الضريبيّة، وبيانُ
/// الخصوصيّةِ لآبل، وصلابةُ الإقلاع. وأربعةٌ وأربعون تَعضّ.
///
/// **وليس فرضيّاً:** هذا المستودعُ شُحِنَ على هذا بعينِه مرّةً — أوّلُ صياغةٍ
/// لحارسِ `google_fonts` «عدَّت ثلاثةَ آباءٍ من `Platform.resolvedExecutable`
/// … فلم تَجِدْ شيئاً ورجعت مبكراً — **خضراءَ وجوفاء**». وطرائقُ الإفراغِ
/// عمليّةٌ: نقلُ مجلّدٍ أو إعادةُ تسميتِه، أو مُرشِّحٌ يَضيق، أو تشغيلٌ من
/// جَذرٍ آخر. وأحدُ العشرينَ حارسٌ كُتبَ في الجلسةِ نفسِها.
///
/// العلاجُ أنّ التعدادَ يَمُرُّ بـ`sourcesIn` و**الأرضيّةُ وسيطٌ مطلوب**، فلا
/// موضعَ نداءٍ منسيٌّ يَبقى على السلوكِ القديمِ بصمت. والقياسُ أُعيد بعدَه:
/// العشرونَ كلُّها تَعضُّ الآن.
///
/// **وهذا الفحصُ نصفُ البرهان، ويُقالُ كذلك:** البرهانُ الحقيقيُّ هو القضمُ
/// أعلاه ولا يُمكِنُ أن يَسكنَ المجموعةَ (فحصٌ لا يُشغّلُ نفسَه مُقضَّماً).
/// فما يُشَدُّ هنا: أنّ الأرضيّةَ تَعملُ **سلوكاً**، وأنّ المُعدِّدَ المشترَكَ
/// ما زال مُستعمَلاً ولم يَخرُجْ من الخدمة، وأنّ كلَّ حارسٍ يَعُدُّ بنفسِه
/// يَحملُ أرضيّةً في ملفِّه.
void main() {
  group('الأرضيّةُ سلوكاً — لا اسماً', () {
    test('مجلّدٌ غائبٌ يَرمي ولا يُعيدُ قائمةً فارغة', () {
      expect(() => sourcesIn('lib/no_such_dir_xyz', atLeast: 1),
          throwsA(isA<StateError>()),
          reason: 'انتقالُ مجلّدٍ كان يُنتجُ مسحاً صامتاً على لا شيء');
    });

    test('ومسحٌ دونَ الأرضيّةِ يَرمي', () {
      expect(() => sourcesIn('lib', atLeast: 999999),
          throwsA(isA<StateError>()),
          reason: 'الأرضيّةُ هي كلُّ ما يُميّزُ المسحَ الحيَّ من الجوفاء');
    });

    test('والمسحُ السليمُ يُعيدُ ملفّاتِه', () {
      final files = sourcesIn('lib', atLeast: 100);
      expect(files.length, greaterThanOrEqualTo(100));
      expect(files.every((f) => f.path.endsWith('.dart')), isTrue);
      // ومُرشِّحُ الامتدادِ يَعمل.
      expect(sourcesIn('functions', atLeast: 1, exts: const ['.json'])
          .every((f) => f.path.endsWith('.json')), isTrue);
    });

    test('والأرضيّةُ وسيطٌ مطلوبٌ لا مُفترَض', () {
      final src = File('test/helpers/sources_in.dart').readAsStringSync();
      expect(src, contains('required int atLeast'),
          reason: 'قيمةٌ افتراضيّةٌ تُعيدُ العطلَ بصمتٍ عند نداءٍ منسيّ');
    });
  });

  group('النطاق', () {
    /// كلُّ ملفِّ حارسٍ في `test/`.
    List<File> guards() => sourcesIn('test', atLeast: 100)
        .where((f) => f.path.endsWith('_test.dart'))
        .toList();

    test('والمُعدِّدُ المشترَكُ ما زال مُستعمَلاً — لا خرجَ من الخدمة', () {
      final users = guards()
          .where((f) => f.readAsStringSync().contains('sourcesIn('))
          .map((f) => f.path)
          .toList();
      expect(users.length, greaterThanOrEqualTo(20),
          reason: 'العشرونَ المُصلَحةُ عادت تَعُدُّ بنفسِها — $users');
    });

    test('وكلُّ حارسٍ يَعُدُّ بنفسِه يَحملُ أرضيّةً في ملفِّه', () {
      // بديلٌ نصّيٌّ عن القضمِ (وهو البرهان): لا يُثبِتُ أنّ الأرضيّةَ على
      // العددِ المسوحِ بعينِه، لكنّه يَكشفُ الحالةَ الشائعة — تعدادٌ بلا أيِّ
      // حدٍّ أدنى في الملفِّ كلِّه، وهي حالُ العشرينَ قبلَ الإصلاح.
      final naked = <String>[];
      for (final f in guards()) {
        final s = f.readAsStringSync();
        if (!s.contains('listSync')) continue;
        final hasFloor = s.contains('greaterThanOrEqualTo(') ||
            RegExp(r'greaterThan\(\s*\d').hasMatch(s) ||
            s.contains('isNotEmpty');
        if (!hasFloor) naked.add(f.path);
      }
      expect(naked, isEmpty,
          reason: 'تعدادٌ بلا أرضيّةٍ — مسحٌ يَنحلُّ يَمُرُّ أخضرَ: $naked');
    });
  });
}
