/// **عرضُ المال: قاعدةٌ واحدةٌ لكلِّ جهة — مرآةُ `formatSar` في**
/// `lib/utils/home_packages.dart`.
///
/// الرقمُ في Firestore قد يكون `int` أو `double` بحسبِ مَن كتبَه، ومحرِّرا
/// الإدارةِ يَكتبانِ `double.tryParse(...) ?? 0.0` — فسعرُ ٣٥ يُخزَّنُ `35.0`.
/// وقد أُصلِحَ ذلك في التطبيقِ في **٢٤ موضعاً** بقاعدةٍ واحدة (صحيحٌ بلا
/// كسور، وإلّا خانتان)، **واللوحةُ بَقيت بثلاثِ صِيَغٍ مختلفة**:
///
///   • `formatCurrency` في `Accountants.tsx` وحدَها:
///     `toLocaleString('ar-SA', {maximumFractionDigits: 0})` — تُسقِطُ
///     الهللاتَ من «الإيراد» و«صافي الأرباح» و«الرواتب»، وتَكتبُ أرقاماً
///     عربيّةً-هنديّةً وحدَها في لوحةٍ أرقامُها كلُّها لاتينيّة.
///   • `sar()` في `serviceMeta.ts`: `toFixed(2)` دائماً — «35.00 ر.س».
///   • وتسعةُ مواضعَ **خامّةٍ** (`{product.price} ر.س`) — «172.5 ر.س».
///
/// فالمبلغُ الواحدُ يُقرأُ «١٧٢٬٥٠٠» و«172.50» و«172.5» في اللوحةِ نفسِها،
/// و«172.50» في التطبيق.
///
/// **وإسقاطُ الكسورِ قرارٌ سبقَ أن سُمّي عطلاً في هذا المستودع**: تعليقُ
/// `formatSar` يَقول «الرقاقةُ والملخّصُ يَعرضانِ **نفس** الرقمِ الذي يُدفَع
/// (كان تقريبُ الرقاقةِ لصفرِ كسورٍ يُظهرُ سعراً يُخالِفُ الفاتورة)» — وهو
/// بعينُه ما تَفعلُه `formatCurrency` بأرقامِ المحاسب، فرقمُ «صافي الأرباح»
/// المعروضُ ليس الرقمَ المحسوب.
///
/// وجدولُ الحالاتِ مشترَكٌ مع فحصِ الدارت (`money.test.ts` ↔
/// `test/money_format_test.dart`) فلا تَفترقُ الجهتان بصمت.

/// صحيحٌ بلا كسور، وإلّا خانتان — حرفيّاً قاعدةُ `formatSar` في الدارت.
export function formatSar(v: number): string {
  if (!Number.isFinite(v)) return '0';
  return v === Math.round(v) ? v.toFixed(0) : v.toFixed(2);
}

/// نفسُ القاعدةِ لقيمةٍ آتيةٍ من مستندٍ (نظيرُ `formatSarAny`).
export function formatSarAny(v: unknown): string {
  const n = typeof v === 'number' ? v : Number.parseFloat(String(v ?? ''));
  return formatSar(Number.isFinite(n) ? n : 0);
}
