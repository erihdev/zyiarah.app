// حالةُ الكوبون — **القاعدةُ قاعدةٌ لا تعداد**، ومفردةٌ واحدةٌ للتعطيل.
//
// الخادمُ يَحكمُ بـ`coupons.js`: `if (coupon.status && coupon.status !== "active")`
// — فأيُّ قيمةٍ غيرِ `active` تُعطّلُ الكوبون، **والغيابُ نشاطٌ**.
//
// وهذه اللوحةُ كانت تَكتبُ `'expired'` للتعطيل بينما محرّرُ تطبيقِ الإدارةِ
// يَكتبُ `'inactive'` — وكلاهما يُعطّلُ خادميّاً، فالقرارُ سليم. لكنّ صفَّ
// الجدولِ هنا كان يَختبرُ `status === 'expired'` وحدَها: كوبونٌ عُطّل من
// التطبيقِ (`'inactive'`) **لا يُعتَم**، فيَبدو مُفعَّلاً في جدولٍ زرُّه
// يَعرضُ «تفعيل» — إشارتانِ متعارضتانِ في صفٍّ واحد.
//
// و`'expired'` اسمٌ سيّئٌ للتعطيلِ اليدويِّ أصلاً: `expiry` حقلٌ مستقلٌّ،
// فلا يُفرَّقُ بين كوبونٍ أوقفَه الأدمنُ وآخرَ انتهى تاريخُه.

/** القيمةُ الوحيدةُ التي تُعَدُّ نشاطاً. */
export const COUPON_ACTIVE = 'active';
/** والمفردةُ الواحدةُ للتعطيلِ اليدويّ — نفسُ ما يَكتبُه محرّرُ التطبيق. */
export const COUPON_DISABLED = 'inactive';

/** نشطٌ = `active` أو غائب (نفسُ قراءةِ الخادم). */
export function couponIsActive(status?: string | null): boolean {
  return !status || status === COUPON_ACTIVE;
}
