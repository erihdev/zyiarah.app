// انتهاءُ الكوبونِ — مرآةُ الجانبِ الكاتبِ لما تَقرؤه `functions/coupons.js`.
//
// حقلُ `<input type="date">` يُعيد نصّاً (`"2026-12-31"`)، واللوحةُ كانت تَكتبه
// **خاماً** في `promo_codes.expiry` بينما محرّرُ Flutter يَكتب `Timestamp`.
// وفحصُ الخادمِ كان `typeof c.expiry.toMillis === "function"` — فالنصُّ لا
// يَملكُ `toMillis` و**الفحصُ يُتخطّى كلَّه**: كلُّ كوبونٍ أُنشئ من اللوحةِ
// كان بلا انتهاءٍ خادميّاً. (العميلُ يَفحصُ النوعَين، فكانت الواجهةُ أصرمَ من
// الخادم.)
//
// ولا تُستعمل `new Date("2026-12-31")`: تلك تُفسَّر **UTC منتصفَ الليل** — أي
// 03:00 بالرياضِ في **بدايةِ** اليوم. فبطاقةٌ تقول «ينتهي 2026-12-31» كان
// كوبونُها ميتاً صبحَ ذلك اليوم. البناءُ من المكوّناتِ وآخرُ لحظةٍ من اليومِ
// مقصودان: `expiry` يُقارَن `exp < now`، فآخرُ اللحظةِ يَجعلُ اليومَ المكتوبَ
// يومَ عملٍ كاملاً كما تَقرؤه الأدمن.

/** آخرُ لحظةٍ من يومٍ بصيغة `YYYY-MM-DD` بالتوقيتِ المحلّيّ. */
export function endOfLocalDay(ymd: string): Date {
  const [y, m, d] = String(ymd).split('-').map(Number);
  if (!y || !m || !d) return new Date(NaN);
  return new Date(y, m - 1, d, 23, 59, 59, 999);
}
